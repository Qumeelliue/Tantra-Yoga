// ЭКРАНЫ ГОРОДА СОБРАНЫ И ПОКАЗАНЫ.
//
// ## Зачем этот файл
//
// В сессии 28 нашлась левая колонка Поля Ума: счётчик монет, счётчик севы,
// список реликвий и цифра щита были написаны в коде, собраны в разметку — и
// НИКОГДА не вставлены на экран. Четыре обещания, четыре молчания, и ни один
// тест этого не видел: все проверяли, что функция возвращает разметку.
//
// Класс поломки общий: **функция собрала — не значит показала**. Поэтому здесь
// берётся уже СОБРАННЫЙ экран (тот же `show`, который рисует игрок), и по нему
// идут вопросы: что на экране, что кликабельно, что обещано, но не показано.
//
// ## Правила этого файла
//
// 1. Ищем по КЛАССУ и по структуре состояния, а не по словам. «Фонтан юности»
//    на экране — не признак того, что это фонтан: то же слово может стоять в
//    подсказке на другом экране.
// 2. Каждая проверка сформулирована как обещание игроку: «игрок видит цену»,
//    «игрок видит, что купил», «игрок может уйти».
// 3. Цена видна ЧИСЛОМ. «Сколько-нибудь» — это не цена.

import { describe, it, expect, beforeAll } from 'vitest'

let dom = null
let helper = null
let text = () => ''
let targets = () => []

beforeAll(async () => {
  helper = await import('./helpers/dom.js')
  dom = helper.installDom()
  await import('@webapp/js/main.js')
  targets = () => helper.clickables(dom.root)
  text = () => helper.textOf(dom.root)
})

const byText = (re) => {
  const n = targets().find((x) => re.test(helper.textOf(x)))
  if (!n) return false
  n.dispatch('click')
  return true
}

const byClass = (re) => {
  const n = targets().find((x) => re.test(String(x.className || '')))
  if (!n) return false
  n.dispatch('click')
  return true
}

const q = (sel) => dom.root.querySelector(sel)
const qa = (sel) => dom.root.querySelectorAll(sel)

/**
 * Дойти до титула.
 *
 * Возврат с любого экрана идёт кнопкой «← …», и названия у неё разные:
 * «← Назад», «← Город», «← уйти». Первая версия искала только «← Назад» и на
 * экране чакр (где кнопка называется «← Город») останавливалась — проверка
 * сообщала «до титула не дошли» там, где титул был в одном нажатии.
 */
function goTitle(limit = 12) {
  for (let i = 0; i < limit; i++) {
    if (/В путь по миру/.test(text())) return true
    if (!byText(/Понятно|Начать|Далее|Дальше|← /)) return false
  }
  return /В путь по миру/.test(text())
}

describe('Титул: путь в игру есть и он назван', () => {
  it('титул открывается и на нём есть вход в Поле Ума', () => {
    expect(goTitle(), `до титула не дошли; экран: ${text().slice(0, 120)}`).toBe(true)
    expect(targets().some((x) => /В путь по миру/.test(helper.textOf(x))),
      'на титуле нет входа в Поле Ума').toBe(true)
  })

  it('второй путь назван честно, а не спрятан под другим словом', () => {
    // Кнопка «Колода — второй путь» обязана называть, что это второй путь:
    // иначе игрок думает, что это главная игра, и уходит не туда.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(/Колода — второй путь/.test(text()),
      'второй путь не назван на титуле').toBe(true)
  })

  it('на титуле видны Город и Мастерская — иначе возвращаться незачем', () => {
    // Город и Мастерская — единственное, ради чего игрок выходит из забега.
    // Если их не видно с титула, выход выглядит бесполезным.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(/Мастерская/.test(text()), 'на титуле нет входа в Мастерскую').toBe(true)
    expect(/Город|Грантха/.test(text()), 'на титуле нет входа в Город').toBe(true)
  })

  it('нажатие входа действительно ведёт в Поле Ума, а не никуда', () => {
    // Кнопка, которая ничего не открывает, хуже отсутствующей: игрок нажал и
    // решил, что игра сломалась.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(byText(/В путь по миру/), 'не открылся вход в Поле Ума').toBe(true)
    expect(/Кем ты идёшь|Фонтан|Поле Ума/.test(text()),
      `вход не привёл в Поле Ума; экран: ${text().slice(0, 120)}`).toBe(true)
  })
})

describe('Мастерская севы: покупка объяснена на карточке', () => {
  it('мастерская открывается с титула и на ней есть усиления', () => {
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(byText(/Мастерская/), 'не открылась Мастерская').toBe(true)
    const rows = qa('.ws-row')
    expect(rows.length, `на мастерской нет ни одного усиления; экран: ${text().slice(0, 140)}`)
      .toBeGreaterThan(3)
  })

  it('на каждом усилении видно, что оно меняет', () => {
    // Правило §8.1 проекта: у всякой покупки есть предмет. Здесь предмет — сама
    // строка усиления, и она обязана говорить, что меняется, иначе очки севы
    // тратятся вслепую.
    for (const r of qa('.ws-row')) {
      const tx = helper.textOf(r.querySelector('.ws-tx'))
      expect(String(tx || '').length,
        `усиление без описания: ${String(tx || '').slice(0, 40)}`).toBeGreaterThan(10)
    }
  })

  it('цена видна числом, и у купленного написано «изучено»', () => {
    const costs = qa('.ws-cost')
    expect(costs.length, 'у усилений нет цены').toBeGreaterThan(0)
    for (const c of costs) {
      const s = String(c.textContent || '')
      expect(/изучено|\d+ сева/.test(s), `цена нечитаема: «${s}»`).toBe(true)
    }
  })

  it('накопленные очки севы видны — иначе непонятно, на что тратить', () => {
    const pts = q('.ws-points')
    expect(pts, 'на мастерской нет счётчика очков севы').toBeTruthy()
    expect(/\d/.test(String(pts.textContent || '')),
      `счётчик очков севы без числа: «${String(pts.textContent || '')}»`).toBe(true)
  })

  it('из мастерской есть выход', () => {
    // Экран без выхода — ловушка: игрок зашёл и не может вернуться.
    expect(byText(/← Назад/), 'из Мастерской некуда выйти').toBe(true)
  })
})

describe('Фонтан юности: нефрит выбирается и ранг покупается', () => {
  beforeAll(() => { goTitle() })

  it('фонтан открывается и на нём есть нефрит на выбор', () => {
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(byText(/В путь по миру/), 'не открылся вход в Поле Ума').toBe(true)
    // Варна → почерк → фонтан.
    byClass(/wsel-card/)
    byClass(/wsel-card/)
    const stones = qa('.jade-card')
    expect(stones.length, `на фонтане нет нефрита; экран: ${text().slice(0, 140)}`).toBeGreaterThan(0)
  })

  it('на нефрите написано, что он меняет — правило на самой карточке', () => {
    for (const s of qa('.jade-card')) {
      const desc = helper.textOf(s.querySelector('.boon-desc'))
      expect(String(desc || '').length,
        `нефрит без описания: ${String(desc || '').slice(0, 40)}`).toBeGreaterThan(10)
    }
  })

  it('возврат из смерти обещан ЗДЕСЬ, а не на экране смерти', () => {
    // Обещание, которое нельзя исполнить в момент выбора, — сюрприз. Значит
    // правило возврата должно быть видно до забега. И не абзацем: одна строка.
    const hint = q('.record-hint')
    expect(hint, 'на фонтане нет обещания возврата из смерти').toBeTruthy()
    expect(/вернуться/i.test(String(hint.textContent || '')),
      `обещание возврата есть, но не о возврате: «${String(hint.textContent || '').slice(0, 60)}»`).toBe(true)
  })

  it('ранг нефрита либо куплен за монеты, либо честно помечен как высший', () => {
    // Покупка ранга — это трата монет. Если кнопки нет и слова «высший ранг» нет,
    // игрок видит карточку, на которой нечего нажать, и не понимает почему.
    const ups = qa('.jade-up')
    const maxed = qa('.jade-rank')
    expect(ups.length + maxed.length,
      `на нефрите нет ни кнопки ранга, ни «высшего ранга»: ${text().slice(0, 140)}`)
      .toBeGreaterThan(0)
    for (const b of ups) {
      expect(/\d+ монет/.test(String(b.textContent || '')),
        `кнопка ранга без цены: «${String(b.textContent || '')}»`).toBe(true)
    }
  })
})