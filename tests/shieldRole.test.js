// ЩИТ НЕ ЗАМЕНЯЕТ ДЕФЛЕКТ — И ЭТО ИЗМЕРЕНО, А НЕ НАДЕЕТСЯ.
//
// ## Что здесь защищается
//
// В игре два защитных слоя: дефлект (главный глагол) и щит. Щит закрывает 72 %
// урона — на глаз он выглядит так, будто держит игру, а дефлект нужен для вида.
// Замерено на 80 забегов:
//
//   | режим                | побед |
//   |-----------------------|-------|
//   | дефлект + щит        | 79 %  |
//   | дефлект, без щита    | 29 %  |
//   | щит, без дефлекта     | **0 %** |
//   | ни того, ни другого   | **0 %** |
//
// Ни один слой не работает в одиночку. Это и есть то, что делает дефлект
// обязательным, а игру — игрой, а не «набери щит и стой».
//
// ## Почему это тест, а не замер в документе
//
// Потолок щита поднимался с 12 до 16 (см. комментарий в `field.js`: при 12
// сева впустую составляла 12 %). Поднятие потолка — это ровно тот вид правки,
// который мог бы тихо сломать зависимость: больше щита → дефлект стал меньше
// нужен. Проверка после правки показала 0 % без дефлекта — зависимость держится.
// Теперь это зафиксировано, чтобы следующая правка потолка не прошла мимо.
//
// ## Грязная половина того же файла
//
// В замере есть два флага сравнения, и один из них легко принять за работающий:
// `--shield=off` и `--parry=off`. Если передать их одной строкой без пробела между
// словами, замер получит один несуществующий флаг и напечатает результат базовой
// игры — то есть правдоподобный вывод о несуществующем эффекте. Проверка ниже
// требует, чтобы оба флага читались раздельно.

import { it, expect, beforeAll } from 'vitest'
import { describeSlow } from './helpers/slow.js'
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { DEFAULT_FIELD_OPTIONS } from '../webapp/js/core/field.js'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8')

function runSim(args, runs = 20) {
  return execFileSync('node',
    ['--experimental-loader', './scripts/aliases.mjs', 'scripts/fieldBalance.mjs', String(runs), ...args],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 300000 })
}

const winsOf = (out) => {
  const m = out.match(/побед: (\d+) \((\d+)%\)/)
  return m ? { n: Number(m[1]), pct: Number(m[2]) } : null
}
const wastePctOf = (out) => {
  const m = out.match(/впустую \(щит полон\) \d+ — (\d+)%/)
  return m ? Number(m[1]) : null
}
const shieldPctOf = (out) => {
  const m = out.match(/съел \d+ урона из \d+ \((\d+)%\)/)
  return m ? Number(m[1]) : null
}

let base = null

describeSlow('Щит не заменяет дефлект', () => {
  beforeAll(() => { base = runSim(['--sloppy=0.85', '--seva']) })

  it('замер в базовом режиме вообще говорит про щит', () => {
    // Проверка на «измеритель, который молчит». Если строка про щит исчезнет,
    // все следующие проверки станут зелёными на нуле, и это будет выглядеть как
    // «щит перестал работать» вместо «щит перестали мерить».
    expect(shieldPctOf(base), 'замер не печатает, сколько урона съел щит').not.toBeNull()
    expect(shieldPctOf(base), 'щит не сработал ни разу — база сломана').toBeGreaterThan(20)
  })

  it('щит без дефлекта не выигрывает ни одного забега', () => {
    // Главная защита. Если это перестанет быть 0 %, то дефлект стал необязательным
    // и главный глагол игры можно не нажимать.
    const out = runSim(['--sloppy=0.85', '--seva', '--parry=off'])
    const w = winsOf(out)
    expect(w, 'замер без дефлекта не напечатал побед').toBeTruthy()
    expect(w.pct, `без дефлекта выиграно ${w.pct}% — щит стал заменой главного глагола`).toBe(0)
  })

  it('дефлект без щита тянет, но один — и в этом суть', () => {
    const out = runSim(['--sloppy=0.85', '--seva', '--shield=off'])
    const w = winsOf(out)
    expect(w, 'замер без щита не напечатал побед').toBeTruthy()
    expect(shieldPctOf(out), 'без щита урон всё равно кто-то съел — флаг не сработал').toBe(0)
    // Слой тянет, но недостаточно: значит дефлект и щит делят работу, а не
    // подменяют друг друга. Точное число здесь не проверяется — оно внутри шума.
    expect(w.pct, 'дефлект без щита выигрывает больше, чем половина — щит не нужен вовсе')
      .toBeLessThan(winsOf(base).pct)
  })

  it('без обоих слоёв не выигрывает ничего', () => {
    const out = runSim(['--sloppy=0.85', '--seva', '--shield=off', '--parry=off'])
    expect(winsOf(out).pct).toBe(0)
  })

  it('базовый режим лучше каждого слоя по отдельности', () => {
    const b = winsOf(base).pct
    const noShield = winsOf(runSim(['--sloppy=0.85', '--seva', '--shield=off'])).pct
    expect(b, `в базе ${b} % — дефлект и щит вместе хуже, чем дефлект один (${noShield} %)`)
      .toBeGreaterThan(noShield)
  })
})

describeSlow('Потолок щита подобран, а не назначен', () => {
  it('сева, потраченная впустую, держится ниже 8 %', () => {
    // При потолке 12 было 12 %: игрок отдавал севу просящему и не получал
    // ничего. Это и есть та причина, по которой потолок поднят.
    const w = wastePctOf(base)
    expect(w, 'замер не печатает, сколько севы потрачено впустую').not.toBeNull()
    expect(w, `сева впустую ${w} % — игрок снова платит за пустоту`).toBeLessThan(8)
  })

  it('щит ещё и работает: он ест большую часть урона', () => {
    // Если доля урона, съеденного щитом, упала ниже половины, то щит перестал
    // быть вторым слоем — и тогда обе цифры выше (0 % без дефлекта, waste < 8 %)
    // перестают про него говорить.
    expect(shieldPctOf(base), 'щит ест меньше половины урона').toBeGreaterThan(50)
  })

  it('потолок в игре — 16, и это зафиксировано числом в тесте', () => {
    // Замысел числа живёт здесь. Правка потолка обязана ронять эту проверку,
    // чтобы её нельзя было сделать молча.
    expect(DEFAULT_FIELD_OPTIONS.shieldMax).toBe(16)
  })
})

describeSlow('Флаги щита читаются раздельно', () => {
  it('оба флага объявлены, и каждый о своём', () => {
    const sim = read('scripts/fieldBalance.mjs')
    expect(sim).toMatch(/--shield=off/)
    expect(sim).toMatch(/--parry=off/)
    // И строки вывода щита обязаны называть потолок, по которому СЧИТАЛИСЬ:
    // раньше печаталось «максимум 24 из потолка 12» — число из другой
    // конфигурации, которого в игре нет.
    expect(sim, 'строка щита печатает потолок из другой конфигурации')
      .not.toMatch(/максимум \$\{SHIELD\.max\} из потолка \$\{DEFAULT_FIELD_OPTIONS\.shieldMax\}/)
  })

  it('замер печатает потолок, по которому считал', () => {
    const out = runSim(['--sloppy=0.85', '--seva', '--shield-cap=24'])
    expect(out, 'при своём потолке замер печатает чужой').toContain('из потолка 24')
    expect(out, 'при своём потолке замер печатает чужой').not.toContain('из потолка 12')
  })
})