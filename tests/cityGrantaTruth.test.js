// ГРАНТХА И ГОРОД СОБРАНЫ И ПОКАЗАНЫ.
//
// ## Зачем этот файл
//
// Грантха и Город — два экрана, ради которых игрок выходит из забега. И оба до
// этого отрезка не были проверены «собранным экраном»: тесты смотрели, что
// функции возвращают разметку, а на экране её могло не быть. Так уже было с
// левой колонкой Поля Ума (четыре счётчика собраны и **не вставлены**) и с
// финалом (обещан и **недостижим**).
//
// ## Что проверяется
//
// 1. **Грантха показывает счётчики «собрано N/M»** — иначе коллекционирование не
//    видно и незачем. Это ровно то, что игрок проверяет, открывая её.
// 2. **Вкладки переключаются и содержимое меняется** — экран с четырьмя вкладками,
//    где все четыре показывают одно и то же, выглядит как готовый.
// 3. **Закрытая цитата видна как закрытая** — иначе игрок не понимает, что ещё
//    можно открыть, и Грантха выглядит пустой.
// 4. **Город показывает площади и говорит, что с ними делать** — включая тёмные
//    (иначе непонятно, что за «спит во тьме неведения»).
// 5. **Из обоих экранов есть выход** — экран без выхода хуже отсутствующего.
//
// ## Правила
//
// Ищем по КЛАССУ и по структуре состояния. Слово «Грантха» есть и на кнопке
// титула, и на самой Грантхе, поэтому по нему искать нельзя.

import { describe, it, expect, beforeAll } from 'vitest'

let dom = null
let helper = null
let text = () => ''
let targets = () => []

beforeAll(async () => {
  helper = await import('./helpers/dom.js')
  dom = helper.installDom()
  await import('@webapp/js/main.js')
  targets = () => helper.clickables(dom.root)
  text = () => helper.textOf(dom.root)
})

const byText = (re) => {
  const n = targets().find((x) => re.test(helper.textOf(x)))
  if (!n) return false
  n.dispatch('click')
  return true
}
const q = (sel) => dom.root.querySelector(sel)
const qa = (sel) => dom.root.querySelectorAll(sel)

function goTitle(limit = 12) {
  for (let i = 0; i < limit; i++) {
    if (/В путь по миру/.test(text())) return true
    if (!byText(/Понятно|Начать|Далее|Дальше|← /)) return false
  }
  return /В путь по миру/.test(text())
}

describe('Грантха собрана', () => {
/** Вкладки Грантхи — по КЛАССУ `comp-tabs`, а не по словам: слово «Цитаты»
 *  есть и на вкладке, и в её содержимом. */
const tabsOf = () => {
  const row = q('.comp-tabs')
  expect(row, 'на Грантхе нет панели вкладок').toBeTruthy()
  return row.childNodes.filter((n) => n.nodeType === 1)
}
  it('открывается с титула: четыре вкладки, и помечена ровно одна', () => {
    // Первая версия требовала, чтобы активной была ПЕРВАЯ вкладка. Это не так:
    // по умолчанию открываются «Цитаты», то есть четвёртая. Настоящее свойство
    // другое и оно ломается так же заметно: помечена ровно одна. Ни нуля (игрок
    // не понимает, где он), ни две (непонятно, какая открыта).
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(byText(/Грантха/), 'Грантха не открылась').toBe(true)
    const tabs = tabsOf()
    expect(tabs.length, `вкладок на Грантхе: ${tabs.length}, а обещано четыре`).toBe(4)
    const active = tabs.filter((t) => /primary/.test(String(t.className || '')))
    expect(active.length, `активных вкладок: ${active.length} — игрок не понимает, где он`)
      .toBe(1)
    expect(helper.textOf(active[0]), 'активна не та вкладка, что открыта по умолчанию').toBe('Цитаты')
  })

  it('вкладки переключаются и содержимое меняется', () => {
    // Экран с четырьмя вкладками, где все четыре показывают одно и то же,
    // выглядит как готовый.
    const before = text()
    tabsOf()[1].dispatch('click')
    const after = text()
    expect(after, 'переключение вкладки ничего не изменило — все вкладки показывают одно')
      .not.toBe(before)
    expect(helper.textOf(tabsOf()[0]), 'после переключения активной стала первая вкладка')
      .not.toBe('')
  })

  it('на вкладке «Враги» видны счётчики «собрано N/M» по трём наборам', () => {
    // Первая версия этой проверки искала счётчики на вкладке «Цитаты» — там их
    // нет, и проверка краснела, указывая на игру вместо себя. Счётчики коллекции
    // живут на «Врагах», потому что наборы — это враги.
    tabsOf()[1].dispatch('click')
    const whole = text()
    expect(whole, `на вкладке «Враги» нет ни одного счётчика «собрано N/M»: ${whole.slice(0, 180)}`)
      .toMatch(/\d+\/\d+/)
    for (const name of ['рипу', 'паши', 'владыки']) {
      expect(whole, `в Грантхе нет набора «${name}»: ${whole.slice(0, 180)}`).toContain(name)
    }
  })

  it('из Грантхи есть выход на титул', () => {
    // Экран без выхода — ловушка. Таких уже проверено четыре.
    const back = targets().filter((x) => /← |Назад|Закрыть/.test(helper.textOf(x)))
    expect(back.length, `в Грантхе нет кнопки выхода; экран: ${text().slice(0, 140)}`).toBeGreaterThan(0)
    back[back.length - 1].dispatch('click')
    expect(/В путь по миру/.test(text()),
      `после выхода из Грантхи мы не на титуле: ${text().slice(0, 120)}`).toBe(true)
  })
})

describe('Город собран', () => {
  it('открывается и показывает все площади — включая тёмные', () => {
    expect(goTitle(), 'до титула не дошли').toBe(true)
    const city = targets().find((x) => /Город/.test(helper.textOf(x))
      && /свет в площадях/.test(helper.textOf(x)))
    expect(city, 'на титуле нет карточки Города со счётчиком площадей').toBeTruthy()
    city.dispatch('click')
    expect(/площадей освещено/.test(text()),
      `в Городе нет счётчика освещённых площадей: ${text().slice(0, 160)}`).toBe(true)
    expect(q('.city-grid'), 'сетка площадей не вставлена в экран Города').toBeTruthy()
  })

  it('под каждой площадью — свой участок с домом, а не эмодзи', () => {
    // Поле Ума стало изометрическим, а Город остался экраном с эмодзи-глифами.
    // Затем под площадями появилась земля, а на земле — дом. Это проверяется по
    // классу `.city-area-plot`, а не по слову: слово «Город» есть и на кнопке
    // титула, и на самом экране.
    const plots = qa('.city-area-plot')
    expect(plots.length, `под площадями нет участков (${plots.length} штук на `
      + `${qa('.city-area').length} площадей) — Город остался экраном с эмодзи `
      + 'рядом с изометрическим боем')
      .toBe(qa('.city-area').length)
    expect(plots.length, 'площадей ноль — проверять нечего').toBeGreaterThan(0)

    // У каждой площади СВОЙ участок. Семь одинаковых прошли бы по «участок
    // есть», но выглядели бы как один и тот же двор в семи экземплярах.
    const urls = plots.map((g) => g.style.backgroundImage || '')
    for (const u of urls) {
      expect(u, 'у площади не задан участок').toMatch(/assets\/town\/plot-\d+\.png/)
    }
    expect(new Set(urls).size, `под площадями ${new Set(urls).size} разных участков `
      + `на ${urls.length} площадей — часть площадей выглядит одинаково`)
      .toBe(urls.length)
  })

  it('спящая площадь темнее зажжённой: «свет в площадях» виден на экране', () => {
    // Подпись обещает, что мир не меняется, а в нём зажигается свет. Если бы
    // состояние не влияло на участок, обещание было бы только словами на экране.
    const filters = qa('.city-area-plot').map((g) => g.style.filter || '')
    expect(filters.length, 'площадей нет').toBeGreaterThan(0)
    for (const f of filters) {
      expect(f, 'у площади не задан фильтр состояния — спит и зажжено выглядят одинаково')
        .toMatch(/brightness/)
    }
    // Хотя бы одна тёмная и хотя бы одна светлая: на первом забеге освещённых
    // площадей нет, и проверка «есть тёмная» иначе прошла бы вхолостую.
    const dark = filters.filter((f) => {
      const m = f.match(/brightness\((\d+)%\)/)
      return m && Number(m[1]) < 100
    })
    const lit = filters.filter((f) => {
      const m = f.match(/brightness\((\d+)%\)/)
      return m && Number(m[1]) > 100
    })
    expect(dark.length, 'нет ни одной спящей площади — проверить, что она темнее, нечем')
      .toBeGreaterThan(0)
    expect(lit.length + dark.length, 'часть площадей без состояния')
      .toBe(filters.length)
  })

  it('тёмная площадь говорит, ЧТО её освобождает, — иначе она выглядит сломанной', () => {
    // Первая версия требовала слова «владыка». Оно и так есть — эпитет «Учитель
    // Муладхары» заменяется на «Владыка Муладхары», и проверка была зелёной даже
    // после того, как подсказку с действием убрали. Откат это показал: проверка
    // ловила не то место.
    //
    // Теперь требуется ДЕЙСТВИЕ: «успокойте этого владыку». Это то, что игрок
    // должен понять, глядя на тёмную площадь: не «кто там», а «что делать».
    const dark = qa('.city-area-dark')
    expect(dark.length, 'нет ни одной тёмной площади — а на первом забеге тёмны все').toBeGreaterThan(0)
    for (const a of dark) {
      const hints = a.childNodes
        .filter((n) => n.nodeType === 1 && /city-area-hint/.test(String(n.className || '')))
        .map((n) => helper.textOf(n))
      expect(hints.length, `у тёмной площади нет ни одной подсказки`).toBeGreaterThan(0)
      expect(hints.some((t) => /успокой|освободи|сними/i.test(t)),
        `тёмная площадь не говорит, что с ней делать: «${hints.join(' / ').slice(0, 80)}»`)
        .toBe(true)
    }
  })

  it('зажжённая площадь говорит, кто за ней стоит, и что с ним говорить', () => {
    // Обещание площади: успокоенный владыка становится УЧИТЕЛЕМ, и поговорить с
    // ним можно. Если это не написано, освещённая площадь ничем не отличается от
    // тёмной, кроме цвета.
    const lit = qa('.city-area-lit')
    if (!lit.length) {
      // На первом забеге освещённых площадей нет — это законное состояние.
      // Молчать нельзя: проверка обязана сказать, что не было проверено.
      expect(true, 'освещённых площадей нет — состояние законное, но проверить было нечего')
      return
    }
    for (const a of lit) {
      const s = helper.textOf(a)
      expect(/учител/i.test(s), `освещённая площадь не называет учителя: «${s.slice(0, 60)}»`).toBe(true)
      expect(/Поговорить|даст ещё|ждёт/.test(s),
        `с освещённой площадью не поговорить: «${s.slice(0, 60)}»`).toBe(true)
    }
  })

  it('благословение показано числом — оно и есть награда за город', () => {
    // Город сулит «+1 саттва на забег за каждого учителя». Если это не число, то
    // либо награды нет, либо игрок не знает, что она будет.
    expect(/% саттвы|саттв/i.test(text()),
      `в Городе нет обещанного благословения числом: ${text().slice(0, 200)}`).toBe(true)
  })

  it('из Города есть выход, и ведёт он туда, откуда пришёл', () => {
    const back = targets().filter((x) => /← /.test(helper.textOf(x)))
    expect(back.length, 'в Городе нет кнопки выхода').toBeGreaterThan(0)
    back[0].dispatch('click')
    expect(/В путь по миру/.test(text()),
      `после выхода из Города мы не на титуле: ${text().slice(0, 120)}`).toBe(true)
  })
})