// БОТ-ПАСИФИСТ УБИВАЛ ОКУ И НЕ ЗНАЛ ОБ ЭТОМ.
//
// Что было. Цель §18 — доля мирных финалов — всегда мерилась на пасифисте,
// боте, который по коду играет за мир. Правило «не добивать» было записано
// списком id: `if (card.id === 'tapah' || card.id === 'krodha')`. Охранялись
// ровно две карты, а `first_effort` (3 урона), `samyama` (8), `tandava` (5),
// `tapasyah` (4) и `dvesha` (5) проходили свободно.
//
// Как это выглядело. Из 100 забегов пасифиста мирных финалов было 58 —
// и это число выдавалось за «мягкость колоды по ахимсе». На деле бот из 56
// неудачных боёв 29 закончил тем, что УБИЛ владыку в первой чакре: в отчёте
// это читалось как «осталось 0 % жизни, спокойствие 0». Плюс «Дар Тапаха»
// (+1 урона к любой практике, engine.js:409) бил даже карту без урона в
// контенте, и проверка по карте была дырявой.
//
// Что стало. Проверка идёт по СУММЕ урона, которую карта реально наносит,
// включая дары. Ни одна карта не может завести оку ниже порога успокоения
// (HP ≤ половины, engine.js `pacifyReady`).
//
// Почему это важно именно здесь. Бот «играет за мир», но убивал оку — значит
// все числа «ахимса 98 % побед, 58 мирных финалов» из спеки и отчётов
// описывали не игру, а этого бота. Настоящая честная цифра: 77 % побед.
// Мирный путь стал ДОРОЖЕ, и это ровно то, что он должен быть.

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { CARDS } from '../webapp/js/core/data.js'

const src = readFileSync(new URL('../scripts/balance.mjs', import.meta.url), 'utf8')
const code = src.split('\n')
  .filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l))
  .join('\n')

/** Все карты, которые наносят урон. Считаем из контента, а не по списку. */
function cardsWithDamage() {
  return Object.values(CARDS).filter((c) => c && c.id && Array.isArray(c.effects)
    && c.effects.some((e) => e.kind === 'damage'))
}

describe('Бот-пасифист не убивает оку', () => {
  it('правило «не добивать» не перечисляет карты по id', () => {
    // Прежняя форма: `card.id === 'tapah' || card.id === 'krodha'`. Любая
    // новая карта с уроном пробивала бы её молча.
    expect(code).not.toMatch(/card\.id === 'tapah'\s*\|\|\s*card\.id === 'krodha'/)
  })

  it('проверка идёт по урону карты, а не по её имени', () => {
    expect(code).toContain('cardDamage')
    expect(code).toMatch(/hits > 0 && e\.hp - hits < e\.maxHp \/ 2/)
  })

  it('учтён и «Дар Тапаха» — он бьёт практику без урона в контенте', () => {
    // engine.js:409 — +1 урона к ЛЮБОЙ практике. Без этого карта без
    // damage в effects всё равно била, и бот убивал оку в 6 забегах.
    expect(code).toContain('tapahDamage')
  })

  it('каждая карта с уроном честно посчитана в cardDamage', () => {
    // Если cardDamage считает только effects[].damage, а урон приходит из
    // другого места, проверка снова станет дырявой — молча и поздно.
    for (const c of cardsWithDamage()) {
      const sum = c.effects.reduce((a, e) => a + (e.kind === 'damage' ? (e.amount || 0) : 0), 0)
      expect(sum, `${c.id} объявлен картой с уроном`).toBeGreaterThan(0)
    }
  })

  it('порог успокоения — половина жизни, и правило знает про неё', () => {
    // pacifyReady в engine.js: `if (e.hp > e.maxHp / 2) return false`.
    // Бот обязан считать с тем же порогом, иначе он «не добивает» не там.
    const eng = readFileSync(new URL('../webapp/js/core/engine.js', import.meta.url), 'utf8')
    expect(eng).toMatch(/e\.hp > e\.maxHp \/ 2\)\s*return false/)
  })
})

describe('Замер мира больше не молчит', () => {
  it('доля мирных финалов печатается и у силового бота', () => {
    // Раньше `pacified` для силы считался и НИКОГДА не печатался. Значит
    // про «мирный финал у обычного игрока» не знал никто: цель §18 мерилась
    // только на пасифисте, который по построению играет за мир.
    //
    // Обновлено 2026-09-30 (сессия 24): отчёт печатает ОБА числа и больше
    // не подменяет одно другим.
    //   `peaceful` — забег без единой крови (решение автора, §9.1q). Именно
    //                это теперь считает и игра, и профиль.
    //   `pacified` — все 7 владык успокоены (старое «пробуждение»).
    // Раньше подпись «мирных финалов» стояла над числом `pacified`, то есть
    // отчёт называл «мирным финалом» не то, что игре и профилю.
    expect(code).toContain('мирных финалов: ${peaceful} из ${wins} побед')
    expect(code).toContain('владык успокоено в ${pacified}')
    // Мирный финал по крови обязан быть виден и у пасифиста.
    expect(code).toContain('МИРНЫХ ФИНАЛОВ (забег без единой крови): ${pPeace} из ${pWins} побед')
    // И оба числа считаются по-разному, а не одно выводится из другого.
    expect(code).toContain('peaceful: run.status === \'victory\' && agg.fightKills === 0')
    expect(code).toContain("pacified: run.outcome === 'awakening'")
  })

  it('отчёт говорит, где ломается мирный путь', () => {
    // Без разбора провалов «58 %» — просто число. Провалы показали, что
    // бо��-пасифист убивал владык, и это стоило 29 забегов из 56 неудачных.
    expect(code).toContain('НЕ успокоен')
  })

  it('отчёт различает убийство оки и провал успокоения', () => {
    expect(code).toContain('УБИЛ обычную оку')
    expect(code).toContain('смерти пасифиста')
  })
})