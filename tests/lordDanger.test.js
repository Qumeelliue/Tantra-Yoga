// ТРОН НЕ ДОЛЖЕН ОКАЗЫВАТЬСЯ САМЫМ БЕЗОПАСНЫМ МЕСТОМ ЗАБЕГА.
//
// ## Что здесь измеряется, а не проверяется
//
// Проверок «трон опасен» в этом файле нет и быть не должно: опасность — число,
// а число получается замером. Здесь проверяется одно — **что измерительный
// рычаг не утёк в игру**.
//
// ## Откуда взялось
//
// Замерено (`--lords=all`, парное сравнение на одних семенах, 80 забегов на
// строку): у каждого из 14 владык «0 смертей из 60–80 дошедших». На основном
// прогоне с разбором по типу комнаты:
//
//   смертей в комнате владыки   2 из  512 дошедших  (0.4 %)
//   смертей в обычных комнатах 19 из 1579 дошедших  (1.2 %)
//
// То есть обычная комната втрое смертельнее комнаты владыки — при том, что
// игра строит из трона кульминацию: игрок выбирает владыку из трёх, его имя стоит
// на двери, трон открывает чакру.
//
// ## Почему это не чинится здесь
//
// Потому что вторая половина вопроса не измеряется замером. Бот парирует
// безупречно (об этом замер говорит сам), поэтому «×2 к трону» — это 74 % → 65 %
// побед для робота, а не для человека. Правило проекта: числа поля без слов
// автора не трогаются. Поэтому здесь — измеритель и честная цифра, а не
// изменение баланса.

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import {
  buildFieldFloor, calmMulFor, lordCalmMul, setLordCalmMul, stageHasBoss,
} from '../webapp/js/core/fieldBuild.js'

const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8')

const buildAt = (floor) => {
  const built = buildFieldFloor(floor, { field: { w: 412, h: 600 }, room: 0, rng: () => 0.5 })
  return built.boss
}

describe('Измеритель крепости трона не вмешивается в игру', () => {
  it('вне замера множитель равен единице — игра не читает его вообще', () => {
    // Если бы игра когда-нибудь начала читать этот множитель, замер с `--lord-mul`
    // тихо стал бы правкой баланса, а такой правки никто не подписывал.
    expect(lordCalmMul(), 'множитель трона не единица — он утёк в игру').toBe(1)
  })

  it('единственный, кто его меняет, — замер', () => {
    const callers = []
    for (const f of ['webapp/js/main.js', 'webapp/js/ui/screens/field.js', 'webapp/js/core/field.js']) {
      const s = read(f)
      if (/setLordCalmMul/.test(s)) callers.push(f)
    }
    expect(callers, `рычаг трона вызывается из игры: ${callers.join(', ')}`).toEqual([])
  })

  it('в выводе замера сказано, что́ он измерил', () => {
    const sim = read('scripts/fieldBalance.mjs')
    expect(sim, 'замер не печатает, где кончается забег').toMatch(/где забег кончается/)
    expect(sim, 'в замере нет рычага крепости трона').toMatch(/--lord-mul/)
    // И он обязан печатать предупреждение, когда трон слишком безопасен: иначе
    // цифра «2 смерти из 512» будет просто строчкой в выводе, которую никто не
    // прочитает как проблему.
    expect(sim, 'замер не предупреждает, что владыка ни разу не убил')
      .toMatch(/владыка за 30\+ доходов ни разу не убил/)
  })
})

describe('Трон в игре ровно такой, каким был', () => {
  it('единица не меняет крепость владыки ни на одной чакре', () => {
    setLordCalmMul(1)
    const before = [0, 3, 6].map((f) => buildAt(f)?.calmMax)
    expect(before.every((v) => Number.isFinite(v) && v > 0), 'владыка собран без запаса спокойствия').toBe(true)
    // Меняем на 3 и обратно — единица обязана вернуть ровно те же числа.
    setLordCalmMul(3)
    const harder = [0, 3, 6].map((f) => buildAt(f)?.calmMax)
    expect(harder[0], 'рычаг вообще не работает — кривую построить нечем').toBeGreaterThan(before[0])
    setLordCalmMul(1)
    const after = [0, 3, 6].map((f) => buildAt(f)?.calmMax)
    expect(after, 'единица не вернула исходные числа — рычаг где-то залипает').toEqual(before)
    expect(lordCalmMul()).toBe(1)
  })

  it('плохое значение не ломает сборку комнаты', () => {
    // Замер получает множитель из командной строки. «--lord-mul=» или мусор не
    // должны превращать трон в бессмертного или в ноль.
    for (const bad of ['', 'abc', '-2', '0', 'NaN']) {
      setLordCalmMul(bad)
      expect(lordCalmMul(), `значение «${bad}» принято как множитель`).toBe(1)
      const b = buildAt(0)
      expect(b?.calmMax, `при «${bad}» трон собран без запаса спокойствия`).toBeGreaterThan(0)
    }
    setLordCalmMul(1)
  })

  it('у владыки на всех чакрах есть запас спокойствия и он растёт с чакрой', () => {
    // Трон, который не крепче обычной оки, — не трон. И кривая крепости обязана
    // идти вверх, иначе седьмая чакра от первой не отличается.
    expect(stageHasBoss(0), 'у первой чакры нет владыки').toBe(true)
    const first = buildAt(0).calmMax
    const last = buildAt(6).calmMax
    expect(last, `седьмая чакра не крепче первой: ${first} → ${last}`).toBeGreaterThan(first)
    expect(calmMulFor(6), 'множитель крепости седьмой чакры не вырос').toBeGreaterThan(calmMulFor(0))
  })
})