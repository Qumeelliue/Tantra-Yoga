// АРЕНА И КОМНАТА — ОДНО И ТО ЖЕ ЧИСЛО.
//
// ## Зачем
//
// Рисунок стал ромбом (изометрия), а размер арены остался прямоугольным: 896×448
// — это ромб комнаты, а поле боя при этом 620×900. Что из этого выходит:
//   - оки в нижней трети арены проектировались ЗА нижний угол ромба, то есть за
//     край комнаты: их не было видно и по ним нельзя было ударить;
//   - камера считалась по размерам, которых на экране нет.
//
// Проверка на «оба числа равны» стоит дешевле, а ловит ровно эту поломку. Сделано
// так, чтобы при случайной правке любого из чисел проверка падала, а не
// «рисунок стал чуть кривее».

import { describe, it, expect } from 'vitest'
import { DEFAULT_FIELD_SIZE } from '../webapp/js/core/fieldBuild.js'
import { ROOM_W, ROOM_H, ISO_W, ISO_H, ROOM_TILES, TILE_WORLD } from '../webapp/js/ui/iso.js'

describe('Арена боя = комната на экране', () => {
  it('размер арены совпадает с комнатой по плоскости', () => {
    expect(DEFAULT_FIELD_SIZE.w, 'арена шире комнаты — оки уходят за край ромба')
      .toBe(ROOM_W)
    expect(DEFAULT_FIELD_SIZE.h, 'арена длиннее комнаты — оки уходят за нижний угол')
      .toBe(ROOM_H)
  })

  it('комната собрана из целого числа плиток', () => {
    // Иначе последняя плитка обрезается, и по краю ромба идёт лесенка.
    expect(ROOM_W % TILE_WORLD, `ширина ${ROOM_W} не кратна плитке ${TILE_WORLD}`).toBe(0)
    expect(ROOM_H % TILE_WORLD, `высота ${ROOM_H} не кратна плитке ${TILE_WORLD}`).toBe(0)
    expect(ROOM_W / TILE_WORLD).toBe(ROOM_TILES)
  })

  it('ромб по высоте помещается в телефон, а по ширине — в пределах двух экранов', () => {
    expect(ISO_H, `ромб ${ISO_H} выше экрана 640`).toBeLessThanOrEqual(640)
    expect(ISO_W, `ромб ${ISO_W} — камере есть куда ездить`).toBeLessThan(640 * 2)
  })

  it('мировая единица равна пикселю, иначе радиусы боя едут', () => {
    // Радиус удара 32 в игре обязан быть 32 пикселя на экране: с этим числом
    // палец попадает туда, куда целится, без «коэффициента проекции».
    expect(TILE_WORLD).toBe(64)
  })
})