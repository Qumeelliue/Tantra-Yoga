// Тесты: правило проекта не содержит неправды.
//
// Проверяем ДОКУМЕНТЫ, а не код. Это необычно для набора, и вот почему.
//
// Сессия 24: я сам вписал в AGENTS.md строку «визуал — наши, из Шастр» и
// повторял её три дня как основание. Она оказалась НЕПРАВДОЙ: в шастрах нет
// указаний на цвет, композицию или графику — там философия. Цвета полей на
// самом деле берутся из `content/worlds.json` (поле `element` по чакрам), и
// ссылки на источник там нет.
//
// Зачем это тестом: неправда в правиле опаснее бага. Баг чинится, когда его
// видно. А неправда в правиле — как раз та, на которую не смотрят, потому что
// «так написано». Через месяц на неё опрётся любая правка.
//
// Второе, что здесь ловится: рассогласованность документов. В SPEC §15 стояло
// «мы НЕ копируем», а в AGENTS.md §2 — «копируем 1:1». Оба утверждения были
// на месте одновременно, и читать можно было как угодно.

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'

const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const agents = read('AGENTS.md')
const spec = read('SPEC.md')
const base = read('design/BASE-GAME.md')

/**
 * Снимаем markdown-оформление перед проверкой.
 *
 * Третий раз за час regex цеплялся не к смыслу, а к оформлению: текст написан
 * `**Не** копируем`, проверка искала `Не копируем` и не находила. До этого
 * цеплялась к соседней строке. Общий класс: **проверка обязана видеть то, что
 * утверждается, а не разметку вокруг утверждения.**
 */
const plain = (s) => s.replace(/[*_`]/g, '')

/**
 * Блок цитаты-уточнения в SPEC, где живёт правило копирования.
 *
 * Берём ЦЕЛЫЙ блок цитаты (`> `), а не окно вокруг первого совпадения: в
 * первой версии окно обрезало запрет копировать графику, и проверка честно
 * сказала, что его нет. Проверка искала не там, где правило написано.
 */
function specRule() {
  const i = spec.indexOf('по признаку ПАЛЯЩЕСЯ')
  expect(i, 'в SPEC §15 нет правила копирования').toBeGreaterThan(-1)
  const start = spec.lastIndexOf('\n> ', i)
  const end = spec.indexOf('\n\n', i)
  return spec.slice(start === -1 ? Math.max(0, i - 600) : start, end === -1 ? i + 2000 : end)
}

describe('Правило не приписывает источник тому, чего в источнике нет', () => {
  it('«визуал из Шастр» не подаётся как основание', () => {
    // Проверка ловит **конкретную ложь**, а не слово «визуал». Первая версия
    // ругалась на любой абзац со словом «визуал» и попала на законное
    // «визуального решения — одна из двух строк». Три правки подряд, и все
    // три — regex цеплялся не к утверждению: сначала к соседней строке,
    // потом к markdown-разметке, потом к слову в другом значении.
    //
    // Ложь выглядит так: абзац говорит про визуал/графику/цвет И приписывает
    // источником Шастры, не отрицая этого.
    for (const [name, doc] of [['AGENTS.md', agents], ['BASE-GAME.md', base], ['SPEC', specRule()]]) {
      const paras = plain(doc).split(/\n\s*\n/)
      const false_ = paras.filter((p) => {
        if (/неправд|вычеркнут|пустая формулировка|выдумывать|источника нет/i.test(p)) return false
        const aboutVisual = /визуал|график|цвет/i.test(p)
        const claimsShastra = /(из Шастр|из шастр)/i.test(p)
        return aboutVisual && claimsShastra
      })
      expect(false_, `${name}: абзац приписывает источником Шастры то, чего в них нет: ${false_.join(' / ')}`).toEqual([])
    }
  })

  it('а отменённая формулировка в документах осталась — с явным «неправда»', () => {
    // Обратная проверка: нельзя просто вычеркнуть. Тогда через месяц никто не
    // поймёт, почему формулировка ушла, и напишет её заново.
    // `plain()` обязателен в каждой проверке: четвёртая ошибка подряд была
    // как раз из-за того, что здесь он забыт.
    expect(plain(agents)).toMatch(/«визуал — наши, из Шастр»[\s\S]{0,200}НЕПРАВДОЙ/)
    expect(plain(base)).toMatch(/«визуал — наши, из Шастр», и она была неправдой/)
  })

  it('правило различает «палится» и «не палится», а не «своё/чужое»', () => {
    // Смысл нового правила: видно и сравнивается — не копируем. Наш прежний
    // вариант «смысл наше, структура чужая» не отвечал на вопрос «а что с
    // графикой?», и поэтому её пришлось выдумать в виде «из Шастр».
    expect(agents).toContain('Копируем 1:1 всё, что НЕ палится')
    expect(agents).toContain('НЕ копируем то, что видно и сравнивается')
    expect(agents).toContain('композиция кадра')
    expect(agents).toContain('Почему именно так')
  })

  it('своё разрешено только там, где в Шастрах есть основание', () => {
    expect(agents).toContain('только там, где в текстах ЕСТЬ основание')
    expect(agents).toContain('Не выдумывать источник')
  })
})

describe('Документы не противоречат друг другу', () => {
  it('«мы не копируем» больше не стоит как вывод §15', () => {
    // Оно сидело в SPEC §15, где перечислены игры-источники. Читалось как
    // «мы берём идею, но не делаем как у них» — прямое противоречие
    // AGENTS.md §2 «копируем 1:1». Оба были написаны нами, оба были на месте.
    const bad = spec
      .split('\n')
      .filter((l) => /мы не копируем/i.test(l))
      .filter((l) => !/уточнено|противоречило|читать можно было как угодно/i.test(l))
    expect(bad, 'SPEC §15 всё ещё утверждает, что мы не копируем').toEqual([])
  })

  it('SPEC §15 и BASE-GAME.md говорят одно и то же', () => {
    for (const [name, doc] of [['SPEC §15', specRule()], ['BASE-GAME', base]]) {
      const t = plain(doc)
      expect(t, `${name}: нет признака «палится»`).toContain('ПАЛЯЩЕСЯ')
      expect(t, `${name}: нет запрета копировать графику`).toMatch(/[Нн]е копируем/)
    }
  })
})

describe('Графика обязана иметь строку в BASE-GAME', () => {
  it('запись требование распространено на картинку, а не только на механику', () => {
    expect(agents).toContain('Для графики и композиции запись обязательна')
    expect(agents).toContain('своё, потому что иначе узнают как Y')
    expect(base).toContain('ГРАФИКА: что обязано иметь строку в этом файле')
  })

  it('неправдивая строка помечена честно, а не выкинута', () => {
    // «цвета по чакрам — источника нет» оставлено с пометкой ⚠. Это пример
    // того, как должна выглядеть запись, когда источника нет: не выдумывать
    // основание, а сказать правду.
    expect(base).toContain('цвета полей по чакрам')
    expect(base).toContain('источника нет')
  })

  it('реально скопированные приёмы названы со своим источником', () => {
    // Обратная сторона: нельзя, чтобы «своё» покрыло всё. Проверяем, что
    // скопированное 1:1 действительно названо — иначе правило «сначала копия»
    // перестанет работать незаметно.
    for (const row of ['Nine Sols', 'Hades', 'Slay the Spire']) {
      expect(base, `${row} не назван в записи о графике`).toContain(row)
    }
  })
})
