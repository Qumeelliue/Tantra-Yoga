// МЕДЛЕННЫЕ ПРОВЕРКИ: ТЕ, ЧТО РЕАЛЬНО ЗАПУСКАЮТ ЗАМЕР.
//
// ## Зачем этот файл
//
// Проверки, которые запускают `fieldBalance.mjs` как отдельный процесс, занимают
// секунды, а не миллисекунды. Стандартный таймаут vitest — 5 с на тест, и он
// означал одно: такие проверки падают по таймауту и выглядят как поломка.
//
// Что хуже: их потом начинают «чинить», уменьшая число забегов до двух. Два
// забега ничего не проверяют — с двумя забегами и правило на 80 % побед, и правило
// на 60 % побед, ведут себя одинаково.
//
// Поэтому у медленных проверок один таймаут на весь блок, и он честно велик.
// Число забегов внутри всё равно уменьшается до предела разумного, но не до
// бесполезного.

import { describe } from 'vitest'

/** `describe` с таймаутом на тест, которого хватает запуску замера. */
export function describeSlow(name, fn) {
  return describe(name, fn, 180_000)
}
