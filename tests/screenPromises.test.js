// Тесты: экран не обещает того, чего игра не делает.
//
// Сессия 24 нашла три расхождения такого класса за один проход. Все три были
// не опечатками, а последствиями одной причины: **экран и код правились в
// разное время и в разных местах**, и ничто их не сверяло.
//
//   1. Смерть обещана отнимать нефрит — но не отнимала. Хуже: брала только
//      при одном из двух выходов («к чакрам»), а при втором («ещё раз»)
//      нефрит оставался. Одна смерть — два разных исхода.
//   2. «Убить их нельзя» — а пашу ударом убить можно, и это задумано.
//      Обещание ложно наполовину, и это худшая половина: игрок решает, что
//      его обманули.
//   3. Проверено и оказалось ВЕРНЫМ: «+1 саттва за каждого учителя»
//      (`cityBlessingBonus`). Это закреплено здесь, чтобы правка первых двух
//      не превратилась в повод «на всякий случай переписать» и это.
//
// Правило, которое набор защищает: **обещание игроку — это контракт, и он
// проверяется тестом так же, как механика.** Иначе «убить нельзя» переживёт
// любую правку баланса.

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { ENEMIES } from '@webapp/js/core/data.js'

const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const main = read('webapp/js/main.js')
const field = read('webapp/js/core/field.js')
const city = read('webapp/js/main.js')

/** Ветка кода между двумя маркерами. */
function between(src, from, to) {
  const i = src.indexOf(from)
  if (i < 0) return ''
  const j = src.indexOf(to, i + from.length)
  return src.slice(i, j === -1 ? i + 2000 : j)
}

describe('Смерть отнимает то, что обещала', () => {
  it('«ещё раз» обнуляет нефрит, а не только дары', () => {
    // ГЛАВНАЯ проверка. Здесь была причина расхождения: `runHp` и `boons`
    // обнулялись, а `runKeepsake` — нет. Игрок умирал и молча сохранял
    // нефрит, который по экрану обучения уже не мог иметь.
    const branch = between(main, 'onRetry: (st2) => {', 'onNext: (nextFloor, st2) => {')
    expect(branch, 'ветка «ещё раз» не найдена — разметка изменилась').toContain('finishFieldRun')
    expect(branch, 'жизнь не сбрасывается').toContain('app.runHp = null')
    expect(branch, 'дары не сбрасываются').toContain('app.boons = []')
    expect(
      branch,
      'нефрит не сбрасывается при смерти, хотя экран дважды обещает обратное',
    ).toContain('app.runKeepsake = null')
  })

  it('оба выхода из смерти дают ОДИНАКОВЫЙ результат', () => {
    // Расхождение было ровно здесь: «к чакрам» нефрит обнулял, «ещё раз» —
    // нет. Одна смерть, два разных исхода в зависимости от кнопки.
    const retry = between(main, 'onRetry: (st2) => {', 'onNext: (nextFloor, st2) => {')
    const close = between(main, 'onClose: (st2) => {', '},\n  }))')
    for (const [name, br] of [['ещё раз', retry], ['к чакрам', close]]) {
      expect(br, `${name}: нефрит не обнуляется`).toContain('app.runKeepsake = null')
      expect(br, `${name}: дары не обнуляются`).toContain('app.boons = []')
    }
  })

  it('знание при смерти НЕ теряется — так и обещано', () => {
    // Обратная сторона: чинить нефрит нельзя «заодно» стерев цитаты. Здесь
    // ровно наоборот — знание обязано выжить, и это вторая половина обещания
    // «смерть отнимает нефрит и дары, но не знание».
    const branch = between(main, 'onRetry: (st2) => {', 'onNext: (nextFloor, st2) => {')
    expect(branch, 'цитата места падения не выдаётся при смерти').toContain("placeQuotes('death')")
    // `meta.lived` и `pacifiedBosses` в ветке смерти не трогаются.
    expect(branch).not.toContain('meta.lived = {}')
    expect(branch).not.toContain('meta.pacifiedBosses = []')
  })

  it('обещание про смерть осталось в тексте и теперь правдиво', () => {
    // Текст не меняем — чинится код. Если бы поменяли и текст, то проверка
    // выше перестала бы что-то значить: нефрит можно было бы объявить
    // вечным, и расхождение стало бы неразличимым.
    expect(main).toContain('Смерть отнимает нефрит и дары, но не знание')
  })
})

describe('Экран не врёт про то, кого можно убить', () => {
  it('слово «убить нельзя» больше не обещает того, чего нет', () => {
    // Раньше стояло «Убить их нельзя» — а `field.js` ломает пашу ударом, и
    // это задумано («Пашу можно только сломать силой — и это оставляет
    // самскары»). Обещание ложно наполовину: игрок, убив пашу, решил бы,
    // что его обманули, вместо того чтобы сделать выбор.
    expect(main).not.toContain('Убить их нельзя')
    expect(main).not.toContain("t: 'Убивать нельзя'")
  })

  it('выбор «бить или терпеть» назван прямо и с его ценой', () => {
    // Правка 2026-10-02: абзац на 224 знака сокращён до одной строки. Но
    // ОБЕЩАНИЕ убрать нельзя — это МЕХАНИКА 41 («экран обещал, а код
    // делал иначе»), и оно должно быть сказано ДО выбора. Проверяем смысл,
    // а не прежнюю формулировку: формулировка сокращена намеренно.
    expect(main).toMatch(/рипу сдерживают/i)
    expect(main).toMatch(/пашу ломают|пашу — можно/i)
    expect(main).toContain('самшкару')
  })

  it('но абзаца-инструкции на входе больше нет — подсказки приходят в бою', () => {
    // Обратная сторона той же правки.
    expect(main).not.toMatch(/Ока замахнулась — кольцо сомкнулось/)
    expect(main).not.toMatch(/Терпение или сила — выбор твой/)
  })

  it('и это соответствует коду: рипу удар не ранит, пашу ломает', () => {
    // Проверка текста против механики. Текст — это обещание, и оно обязано
    // совпадать с тем, что реально происходит в бою.
    const strike = between(field, "if (f.kind === 'pasha') {", 'function addShakti')
    expect(strike, 'паша должен терять здоровье от удара').toContain('f.hp -=')
    expect(strike, 'паша должен умирать от удара').toContain('f.dead = true')
    expect(strike, 'удар должен оставлять самскару').toContain('st.samskaraPressure')
    // Ветка рипу — только злость и потеря спокойствия.
    expect(strike).toContain('} else {')
    expect(strike).toContain('f.calm = Math.max(0, f.calm - 0.5)')
  })

  it('рипу физически нечего убивать', () => {
    expect(field).toContain('рипу не имеет ХП: его нельзя убить')
    const rippu = Object.values(ENEMIES).filter((e) => e.kind === 'ripu' || e.isRipu)
    // Проверяем по контенту: у рипу не должно быть боевого здоровья,
    // которое можно было бы пробить. Неполный список — предупреждение,
    // а не падение, если разметка контента изменится.
    for (const e of rippu) {
      if (typeof e.maxHp === 'number') {
        expect(e, `${e.id} объявлен рипу, но у него есть HP`).toBeUndefined()
      }
    }
  })
})

describe('Честные обещания — их нельзя «поправить на всякий случай»', () => {
  it('+1 саттва за каждого учителя — обещание верное', () => {
    // Это единственное обещание из проверенных, которое оказалось правдой.
    // Закрепляем: чтобы правка двух ложных не превратилась в «давай
    // перепишем и это тоже, на всякий случай».
    expect(city).toContain('его благословение (+1 саттва на забег) копится в Городе')
    expect(city).toContain('const cBonus = cityBlessingBonus(app.meta)')
    expect(city).toContain('app.run.gunaStart = { ...g, s: g.s + cBonus }')
  })
})
