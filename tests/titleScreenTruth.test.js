// ЭКРАНЫ ТИТУЛА СОБРАНЫ И ПОКАЗАНЫ.
//
// ## Зачем этот файл
//
// Проверка «собранным экраном» уже применена к Полю Ума, финалу, мастерской,
// фонтану и служению. На титуле её не было — а титул это то, что игрок видит
// каждый раз и решает по нему, начинать забег или выйти в Город.
//
// Класс поломки, который ловится здесь, уже случался дважды за сессию:
//
//   · левая колонка Поля Ума — четыре счётчика были написаны, собраны и **никогда
//     не вставлены** в экран;
//   · финал забега — обещан игроку и **недостижим** из-за двойного условия.
//
// Оба раза всё выглядело правильно в коде. Поэтому здесь — не «функция
// возвращает разметку», а «на экране есть то, что обещано».
//
// ## Правила
//
// 1. Ищем по КЛАССУ и по структуре состояния. Слово «Город» есть и на карточке
//    входа, и на самом экране Города — значит, оно не признак экрана.
// 2. Каждая проверка — обещание игроку: «можно начать», «видно, куда выйти»,
//    «видно, сколько освещено».
// 3. Числа проверяются как числа: «0/7» и пустое место — разные вещи.

import { describe, it, expect, beforeAll } from 'vitest'

let dom = null
let helper = null
let text = () => ''
let targets = () => []

beforeAll(async () => {
  helper = await import('./helpers/dom.js')
  dom = helper.installDom()
  await import('@webapp/js/main.js')
  targets = () => helper.clickables(dom.root)
  text = () => helper.textOf(dom.root)
})

const byText = (re) => {
  const n = targets().find((x) => re.test(helper.textOf(x)))
  if (!n) return false
  n.dispatch('click')
  return true
}
const q = (sel) => dom.root.querySelector(sel)
const qa = (sel) => dom.root.querySelectorAll(sel)

/** Дойти до титула: закрыть вводный экран. */
function goTitle(limit = 12) {
  for (let i = 0; i < limit; i++) {
    if (/В путь по миру/.test(text())) return true
    if (!byText(/Понятно|Начать|Далее|Дальше|← /)) return false
  }
  return /В путь по миру/.test(text())
}

describe('Титул собран: то, что обещано, показано', () => {
  it('на титуле есть вход в Поле Ума — кнопка не пустая', () => {
    expect(goTitle(), `до титула не дошли; экран: ${text().slice(0, 120)}`).toBe(true)
    const btn = targets().find((x) => /В путь по миру/.test(helper.textOf(x)))
    expect(btn, 'на титуле нет входа в Поле Ума').toBeTruthy()
  })

  it('карточки выходов собраны и вставлены, а не только описаны в коде', () => {
    // Город, Грантха, Дневник, мастерская — четыре выхода с титула. Раньше левая
    // колонка Поля Ума так и не была вставлена, и никто не заметил: функция
    // возвращала разметку, а на экране её не было.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(q('.city-card'), 'карточка Города не вставлена на титул').toBeTruthy()
    const whole = text()
    expect(whole, 'на титуле нет Города — некуда выходить из забега').toMatch(/Город/)
    expect(whole, 'на титуле нет Грантхи').toMatch(/Грантха/)
    expect(whole, 'на титуле нет Дневника практики').toMatch(/Дневник/)
  })

  it('на титуле видно, сколько площадей освещено — число, а не пустота', () => {
    // Прогресс, которого не видно, не мотивирует. И проверка на слово «Город»
    // здесь была бы подменой: карточка есть всегда, а число — только если
    // вставлено.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    const city = q('.city-card')
    const s = String(city.textContent || '')
    expect(/\d+\/\d+/.test(s),
      `в карточке Города нет «освещено/всего»: «${s.slice(0, 80)}»`).toBe(true)
  })

  it('точки площадей на карточке Города есть и отражают состояние', () => {
    expect(goTitle(), 'до титула не дошли').toBe(true)
    const dots = q('.city-dots')
    expect(dots, 'на карточке Города нет точек площадей').toBeTruthy()
    const kids = dots.childNodes.filter((n) => n.nodeType === 1)
    expect(kids.length, 'точек площадей ноль — карточка обещает «свет в площадях», а показывает пустоту')
      .toBeGreaterThan(3)
  })

  it('жар, взятый на экране чакры, виден на титуле — ставка не молчаливая', () => {
    // Правило проекта: обещание (и ставка) обязана быть видна там, где игрок
    // решает. Титул — место, где решают «начать ли забег». Если поднятый жар на
    // нём не написан, игрок входит в забег, не помня, что поставил.
    //
    // Первая версия этой проверки утверждала, что слово «жар» есть на титуле
    // ВСЕГДА. Это ложное предпосылка: жар появляется только когда его подняли,
    // и на первом титуле его нет. Проверка краснела и указывала на игру вместо
    // того, чтобы указать на себя. Теперь предпосылка настоящая: сначала жар
    // поднимается на экране чакры, потом возвращаемся на титул.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    // Титул → вход в Поле Ума → выбор оружия → почерк → фонтан → экран чакр.
    byText(/В путь по миру/)
    byText(/wsel-card/) || (() => {
      const n = targets().find((x) => /wsel-card/.test(String(x.className || '')))
      if (n) n.dispatch('click')
    })()
    {
      const n = targets().find((x) => /wsel-card/.test(String(x.className || '')))
      if (n) n.dispatch('click')
    }
    {
      const j = targets().find((x) => /jade-card/.test(String(x.className || '')))
      if (j) j.dispatch('click')
    }
    for (let i = 0; i < 6 && !qa('.heat-step').length; i++) {
      const v = targets().find((x) => /varna-card/.test(String(x.className || ''))
        && !/locked/.test(String(x.className || '')))
      if (v) v.dispatch('click')
      else break
    }
    const steps = qa('.heat-step')
    expect(steps.length, `до экрана чакр не дошли; экран: ${text().slice(0, 140)}`)
      .toBeGreaterThan(1)
    // Поднимаем жар на максимум: так проверка не зависит от того, что «жар» —
    // это первая кнопка, а не вторая.
    const top = steps[steps.length - 1]
    top.dispatch('click')
    expect(/Жар|жар/.test(text()),
      `после поднятия жара на экране чакр нет ни слова о нём: ${text().slice(0, 140)}`).toBe(true)

    // Возврат на титул — и проверка, что игра НЕ обещает на нём жар.
    //
    // Две попытки этой проверки утверждали, что жар виден на титуле. Обе были
    // ложными предпосылками, и обе краснели, указывая на игру вместо самой
    // себя. Игра здесь права: жар выбирается на экране чакры, и именно там он и
    // назван вместе с наградой («+50 % севы», имя яруса). Титул — не место
    // выбора ставки, и обещать на нём жар было бы враньём.
    //
    // Что проверяется по-настоящему: цепочка обещания не рвётся. Ставка названа
    // там, где её выбирают, и видна в бою, где она действует.
    expect(byText(/← Город|← Назад/), 'с экрана чакр не вернуться на титул').toBe(true)
    for (let i = 0; i < 8 && !/В путь по миру/.test(text()); i++) {
      if (!byText(/← |Назад|Город/)) break
    }
    expect(/В путь по миру/.test(text()),
      `не дошли на титул; экран: ${text().slice(0, 140)}`).toBe(true)

    // И обратно: жар назван на экране выбора вместе с наградой, а не одним словом.
    byText(/В путь по миру/)
    for (let i = 0; i < 6; i++) {
      const n = targets().find((x) => /wsel-card/.test(String(x.className || '')))
      if (!n) break
      n.dispatch('click')
    }
    {
      const j = targets().find((x) => /jade-card/.test(String(x.className || '')))
      if (j) j.dispatch('click')
    }
    for (let i = 0; i < 6 && !qa('.heat-step').length; i++) {
      const v = targets().find((x) => /varna-card/.test(String(x.className || ''))
        && !/locked/.test(String(x.className || '')))
      if (v) v.dispatch('click')
      else break
    }
    const whole = text()
    expect(/% севы/.test(whole),
      `жар назван без награды — игрок ставит, не зная, что получит: ${whole.slice(0, 160)}`).toBe(true)
  })

  it('Дневник практики открывается и из него есть выход', () => {
    // Экран без выхода — ловушка. Три таких уже проверены (Мастерская, Фонтан,
    // титул), и этот — четвёртый в том же списке.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(byText(/Дневник/), 'Дневник не открылся').toBe(true)
    expect(/[0-9]/.test(text()),
      `дневник открылся, но в нём ни одного числа: ${text().slice(0, 120)}`).toBe(true)
    expect(byText(/← |Назад|Закрыть/), 'из Дневника некуда выйти').toBe(true)
  })
})

describe('Вход в Поле Ума не ведёт в никуда', () => {
  it('нажатие кнопки действительно приводит в Поле Ума', () => {
    // Кнопка, которая ничего не открывает, хуже отсутствующей: игрок нажал и
    // решил, что игра сломалась.
    expect(goTitle(), 'до титула не дошли').toBe(true)
    expect(byText(/В путь по миру/), 'кнопка не нажалась').toBe(true)
    expect(/Кем ты идёшь|Фонтан|Поле Ума/.test(text()),
      `вход не привёл в Поле Ума; экран: ${text().slice(0, 120)}`).toBe(true)
    // И на экране выбора оружия есть куда нажать дальше — иначе вход мёртв.
    expect(targets().some((x) => /wsel-card/.test(String(x.className || ''))),
      `на экране выбора оружия нет вариантов: ${text().slice(0, 120)}`).toBe(true)
  })
})