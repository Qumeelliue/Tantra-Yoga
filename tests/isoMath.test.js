// ИЗОМЕТРИЯ ДОЛЖНА БЫТЬ ПРОВЕРЯЕМА, А НЕ «КАЖЕТСЯ ПРАВИЛЬНО».
//
// ## Зачем
//
// Изометрию вводили вслепую: снимок экрана здесь не работает, поэтому «похоже на
// Heroes» проверить нечем. Но проекция — это **арифметика**, и арифметику
// проверяется точно, в отличие от картинки.
//
// ## Что здесь проверяется
//
//   1. Ромб ровно вдвое шире своей высоты — иначе это не изометрия, а
//      «скосок», и набор плиток 128×64 к нему не подойдёт.
//   2. Обратная проекция возвращает то, что дала прямая. Ошибка в знаке при
//      пересчёте даёт «палец уходит в другую сторону», и это не видно в коде.
//   3. Глубина растёт монотонно и совпадает с положением ниже по экрану.
//   4. Камера не выходит за ромб: за краем комнаты не пустота, а конец игры.

import { describe, it, expect } from 'vitest'
import {
  TILE_W, TILE_H, ROOM_TILES, ROOM_W, ROOM_H,
  toIso, fromIso, depth, toIsoRoom, isoBounds, ISO_OFFSET_X, depthShade,
} from '../webapp/js/ui/iso.js'

describe('Ромб изометрии — ровно вдвое шире высоты', () => {
  it('соотношение плитки 2:1, как требует набор', () => {
    // Скачанные CC0-наборы изометрии: плитка 128×64. Если наша плитка будет не
    // вдвое, пол ляжет ромбом неправильно — и это не видно глазом.
    expect(TILE_W / TILE_H, `плитка ${TILE_W}×${TILE_H} — наборы требуют 2:1`).toBe(2)
  })

  it('комната в плитках укладывается в ромб, а не в квадрат', () => {
    const a = toIsoRoom(0, 0)
    const right = toIsoRoom(ROOM_W, 0)
    const bottom = toIsoRoom(ROOM_W, ROOM_H)
    const w = isoBounds()
    const rhombW = w.x1 - w.x0
    const rhombH = w.y1 - w.y0
    expect(rhombW / rhombH, `ромб ${rhombW}×${rhombH} — должен быть вдвое шире высоты`)
      .toBeCloseTo(2, 5)
    // Правый нижний угол комнаты — самый близкий к зрителю.
    expect(right.x, 'правый угол должен быть правее верхнего').toBeGreaterThan(a.x)
    expect(bottom.y, 'нижний угол должен быть ниже верхнего').toBeGreaterThan(a.y)
    // Нижний угол ровно под верхним: это самая близкая к зрителю точка ромба.
    expect(bottom.x, 'нижний угол уехал вбок — ромб перекошен').toBeCloseTo(a.x, 6)
  })

  it('высота ромба равна видимой области — камера ездит только вбок', () => {
    // Как в Heroes: комната шире экрана и камера идёт влево-вправо, а вверх-вниз
    // помещается целиком. Если это не так, значит комната слишком мелкая или
    // слишком крупная, и оба случая надо ловить здесь.
    const b = isoBounds()
    expect(b.y1 - b.y0, 'ромб по высоте больше экрана — камера поедет и вверх')
      .toBeLessThanOrEqual(640)
  })
})

describe('Обратная проекция возвращает то же самое', () => {
  it('палец → мир → палец не уплывает', () => {
    // Ошибка в знаке при пересчёте даёт «палец уходит в другую сторону», и в коде
    // это не видно: числа сходятся, а человек тыкает мимо.
    for (const [x, y] of [[0, 0], [ROOM_W, 0], [0, ROOM_H], [ROOM_W, ROOM_H], [123, 456], [ROOM_W / 2, ROOM_H / 2]]) {
      const s = toIsoRoom(x, y)
      const back = fromIso(s.x - ISO_OFFSET_X, s.y)
      expect(back.x, `x разошёлся для (${x}, ${y})`).toBeCloseTo(x, 6)
      expect(back.y, `y разошёлся для (${x}, ${y})`).toBeCloseTo(y, 6)
    }
  })

  it('сдвиг убирает отрицательные координаты — пол не уедет влево', () => {
    // Без сдвига левый угол ромба даёт отрицательный sx, и всё, что рисуется,
    // начинает с минуса. Это выглядит как «графика съехала», а причина — одно
    // число.
    const b = isoBounds()
    expect(b.x0, 'левый край ромба отрицателен — пол уедет за левую границу')
      .toBeGreaterThanOrEqual(0)
    expect(b.y0, 'верхний край ромба отрицателен').toBeGreaterThanOrEqual(0)
  })
})

describe('Глубина: кто дальше, тот позже рисуется', () => {
  it('глубина растёт вместе с положением ниже по экрану', () => {
    // Первая версия брала углы (W,0) и (0,H) — они лежат на одной антидиагонали,
    // и глубина у них одинаковая. Проверка требовала «больше» и падала на верном
    // коде. Ближний угол — (W,H), дальний — (0,0).
    const near = { x: ROOM_W, y: ROOM_H }
    const far = { x: 0, y: 0 }
    expect(depth(near.x, near.y), 'ближний объект должен иметь большую глубину')
      .toBeGreaterThan(depth(far.x, far.y))
    // И на экране «ближе» = «ниже».
    expect(toIsoRoom(near.x, near.y).y).toBeGreaterThan(toIsoRoom(far.x, far.y).y)
  })

  it('глубина монотонна по диагонали', () => {
    let prev = -Infinity
    for (let i = 0; i <= 10; i++) {
      const d = depth(i * 40, i * 40)
      expect(d, `глубина просела на шаге ${i}`).toBeGreaterThan(prev)
      prev = d
    }
  })

  it('затемнение по глубине в пределах разумного', () => {
    // Первая версия проверки вообще не вызывала функцию: сравнивала константы 1 и 0.
    const near = depthShade(ROOM_W, ROOM_H)
    const far = depthShade(0, 0)
    const mid = depthShade(ROOM_W / 2, ROOM_H / 2)
    expect(near, 'ближний край должен быть светлее дальнего').toBeGreaterThan(far)
    expect(mid, 'середина должна быть между краями').toBeGreaterThan(far)
    expect(mid, 'середина должна быть между краями').toBeLessThan(near)
    expect(far, 'дальний край должен быть затемнён, а не чёрный').toBeGreaterThan(0.4)
    expect(near, 'ближний край должен быть полным белым').toBeLessThanOrEqual(1)
  })
})

describe('Комната задана плитками, а не «как получится»', () => {
  it('размер комнаты кратен плитке', () => {
    expect(ROOM_W % TILE_W, `ширина ${ROOM_W} не кратна плитке ${TILE_W}`).toBe(0)
    expect(ROOM_H % TILE_W, `высота ${ROOM_H} не кратна плитке ${TILE_W}`).toBe(0)
    expect(ROOM_W / TILE_W, 'комната должна быть целым числом плиток').toBe(ROOM_TILES)
  })
})