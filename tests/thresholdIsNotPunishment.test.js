// Тесты: порог 50 % не наказывает за добро — он приходит по закону.
//
// Разбор смертей пасифиста (2026-09-30, сессия 24) привёл к порогу
// `onThreshold`. Первая версия разбора сказала: «мирный путь платит за то, что
// дошёл до порога, и +2 силы бьют в спину в момент успеха». Оба вывода были
// неверными, и неверными одинаково:
//
//   1) «Наказание за добро» — чужая формулировка. Карма-йога: «Реакция
//      коэкзистентна действию»; «право на действие, не на плоды» — это отказ
//      ЖЕЛАТЬ плодов, а не отмена их.
//   2) «+2 силы бьют в спину» — свойство КАРТОЧНОГО боя, а не Поля Ума.
//      В Поле Ума порог вообще не наказывает: только фаза 2 и его имя.
//
// Ошиблись мы потому, что два разных боя приняли за один. Тесты ниже не дают
// это повторить: если кто-то решит, что порог наказывает, или попробует
// «уравнять» два пути между собой, набор упадёт.

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { ENEMIES } from '@webapp/js/core/data.js'
import { createField } from '@webapp/js/core/field.js'

const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const code = (p) => read(p)
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/(^|[^:])\/\/.*$/gm, '$1')
const fieldCode = code('webapp/js/core/field.js')
const engineCode = code('webapp/js/core/engine.js')
const baseGame = read('design/BASE-GAME.md')

const BOSSES = Object.values(ENEMIES).filter((e) => e.isBoss)

describe('Порог 50 % есть у всех владык и открывает успокоение', () => {
  it('у каждого владыка порог на половине HP', () => {
    // 21 владыка = 7 чакр × 3 трона (МЕХАНИКА 58). Проверка по числу нужна
    // для того же, для чего была «семь»: если новый трон забыли бы про
    // порог, его не оказалось бы в BOSSES, и набор молча стал бы слабее.
    expect(BOSSES.length).toBe(21)
    for (const b of BOSSES) {
      expect(b.onThreshold, `${b.id} без порога`).toBeTruthy()
      expect(b.onThreshold.trigger, `${b.id}`).toBe('hp_lte_50')
    }
  })

  it('это ровно тот порог, который открывает успокоение — плата за успех', () => {
    // `pacifyReady`: calm полный И HP ≤ половины. То есть сработать порог
    // может ровно тогда, когда игрок уже может успокоить оку. Дойти до конца
    // пути без самскары нельзя — и это не баг, а закон (карма-йога, ch01:
    // «реакция коэкзистентна действию»).
    expect(engineCode).toContain('if (e.hp > e.maxHp / 2) return false')
  })

  it('владыка на пороге раскрывается — и это сказано словами, а не значиками', () => {
    // Главная проверка смысла: логи обязаны звучать как ПРОЯВЛЕНИЕ
    // («сбрасывает маску», «впадает в бешенство»), а не как наказание игроку
    // («наказывает за добро», «бьёт в спину»). Если кто-то перепишет логи в
    // «ты наказан за терпение» — игра станет моралью вместо закона природы,
    // и набор это поймает.
    for (const b of BOSSES) {
      const log = b.onThreshold.log || ''
      expect(log.length, `${b.id} без лога`).toBeGreaterThan(10)
    }
    const words = BOSSES.map((b) => b.onThreshold.log).join(' ')
    // У Ахамкара (7-я чакра) самшкара достаётся самому «я» — сильнее, чем
    // победа. Это осознанная финальная точка. Ищем ПО СПИСКУ, а не по
    // индексу: владык теперь 21, и «седьмой по счёту» больше не значит
    // «Ахамкара» — троны перемешались по чакрам.
    expect(BOSSES.find((b) => b.id === 'ahankara').onThreshold.log).toContain('трон')
  })
})

describe('Поле Ума: порог НЕ наказывает (только фаза 2)', () => {
  it('порог переведён на спокойствие, а не на HP', () => {
    // В Поле Ума нет HP-полосы у оков: там спокойствие. Значит и порог
    // другой — половина ЗАПАСА СПОКОЙСТВИЯ.
    //
    // Проверяем по существу, а не по комментарию: в первой версии теста
    // здесь стояла проверка строки-пояснения `onThreshold: hp_lte_50 →
    // calm_gte_50`. Она в коде есть, но живёт в комментарии — а проверки
    // этого файла читают код БЕЗ комментариев. То есть тест сам себя
    // обманывал: комментарий обещал, а проверка его не видела.
    expect(fieldCode).toContain('f.thresholdAt = f.calmMax * 0.5')
    // Пояснение обязано быть в коде, иначе следующий читатель не поймёт,
    // почему `hp_lte_50` из контента стал `calm_gte_50` в Поле Ума.
    expect(read('webapp/js/core/field.js')).toContain('onThreshold: hp_lte_50 → calm_gte_50')
  })

  it('срыв порога НЕ берёт силу и НЕ подкидывает проклятие', () => {
    // Ключевое различие двух путей. Если бы в Поле Ума начало появляться
    // `+2 силы` или `addCurseToDeck`, то плата за мирный путь переехала бы
    // сюда — а это другой бой с другими правилами. Разбор сессии 24
    // показал, что такой перенос делали дважды (в чтении и в выводе).
    //
    // Граница блока — по ЗАКРЫВАЮЩЕЙ скобке сброса порога, а не по тексту
    // «Оглушение». Иначе блок захватывал пол-файла и находил `strength` и
    // `addCurseToDeck` где-то совсем в другом месте, — проверка проходила бы
    // по чужому коду. Первая версия теста так и делала.
    const start = fieldCode.indexOf('f.thresholdDone = true')
    const end = fieldCode.indexOf('if (f.stun > 0)', start)
    const fn = fieldCode.slice(start, end)
    expect(fn.length, 'блок порога не найден — разметка изменилась').toBeGreaterThan(50)
    expect(fn, 'порог поля не должен давать силу').not.toContain('strength')
    expect(fn, 'порог поля не должен давать проклятие').not.toContain('addCurseToDeck')
  })

  it('а вот зрелищный срыв на месте — заморозка, тряска, его имя', () => {
    const start = fieldCode.indexOf('f.thresholdDone = true')
    const end = fieldCode.indexOf('if (f.stun > 0)', start)
    const fn = fieldCode.slice(start, end)
    expect(fn).toContain('f.phase = 2')
    expect(fn).toContain('st.freeze = Math.max(st.freeze, st.o.hitStopPacify * 1.8)')
    expect(fn).toContain('st.shake = Math.max(st.shake, st.o.shakeBossBreak)')
    expect(fn).toContain('f.thresholdMsg')
  })

  it('порог владыки срабатывает один раз за бой', () => {
    // Иначе «маска срывается» могла бы срываться каждый ход, и терпение
    // было бы невозможно в принципе.
    expect(fieldCode).toContain('!f.thresholdDone && f.thresholdAt')
    expect(fieldCode).toContain('f.thresholdDone = true')
  })
})

describe('Два пути — два разных боя, и это записано', () => {
  it('правило зафиксировано, чтобы порог не «починили»', () => {
    // Без записи следующий читатель увидит «+2 силы в момент успеха» и
    // решит, что это баг. Запись в design/BASE-GAME.md — обязательная часть
    // правки по правилам проекта.
    expect(baseGame).toContain('МЕХАНИКА 39')
    expect(baseGame).toContain('ПОРОГ 50 % НЕ НАКАЗЫВАЕТ ЗА ДОБРО')
    expect(baseGame).toContain('в Поле Ума этого наказания НЕТ')
  })

  it('записано, что переносить свойство одного пути на другой нельзя', () => {
    expect(baseGame).toContain('два разных боя с разными')
    expect(baseGame).toContain('замер одного нельзя переносить на другой')
  })

  it('записана и ОШИБКА разбора, а не только вывод', () => {
    // Правило проекта: неправильный вывод тоже запись. Иначе через месяц
    // кто-то повторит ту же ошибку и решит, что она впервые.
    expect(baseGame).toContain('Ошибка прошлого дня, записанная здесь намеренно')
    expect(baseGame).toContain('два разных мира были')
  })
})

describe('Поле Ума: плата за мирный путь — время и риск, а не яд', () => {
  it('рипу неубиваемы ударом: ломать можно только пашу', () => {
    // Отсюда следует, что «мирный финал» вообще измерим: сломать силой
    // можно только пашу, значит «без единой крови» = «ни одного сломанного
    // паши за забег» (определение автора, §9.1q).
    //
    // Границы — по `function strikeFoe` и её `return ev`: первый вариант
    // искал `f.kind` и находил его мгновенно в той же строке, то есть блок
    // получался длиной 20 символов и проверял чужой код.
    const start = fieldCode.indexOf("if (f.kind === 'pasha') {")
    const fnStart = fieldCode.lastIndexOf('\nfunction ', start)
    const fnEnd = fieldCode.indexOf('\n  return ev', start)
    const fn = fieldCode.slice(fnStart, fnEnd)
    expect(fn.length, 'функция удара не найдена — разметка изменилась').toBeGreaterThan(300)
    // Только паша теряет здоровье и может погибнуть.
    expect(fn).toContain('f.hp -=')
    expect(fn).toContain('f.dead = true')
    // Рипу — только злость и потеря спокойствия, ни одной капли урона.
    // Ветка `else` обязана существовать и обязана говорить это словами:
    // игрок должен ПРОЧИТАТЬ, почему удар не сработал, а не гадать.
    expect(fn).toContain('} else {')
    expect(fn).toContain('f.calm = Math.max(0, f.calm - 0.5)')
  })

  it('удар по паше оставляет самскару — сила не проходит бесследно', () => {
    const start = fieldCode.indexOf("if (f.kind === 'pasha') {")
    const fnEnd = fieldCode.indexOf('\n  return ev', start)
    const fn = fieldCode.slice(start, fnEnd)
    // Не просто «убил и забыл»: ломая чужую жизнь силой, игрок получает
    // давление самскар, и это видно в бою.
    expect(fn).toContain('st.samskaraPressure += 12')
    expect(fn).toContain('сила оставила самскару')
  })
})
