// В ПРОЕКТЕ НЕ ДОЛЖНО ОТЛАДОЧНЫХ ФАЙЛОВ.
//
// ## Зачем
//
// Отладочный тест попал в проект случайно: он печатал замер скорости заливки и
// ничего не проверял. Сам по себе он был безобиден. Но он же объясняет, почему
// ПОЛНЫЙ прогон проверок иногда не заканчивался: файл брал стенд, менял
// глобальное состояние, и следующий за ним файл получал стенд не с того
// состояния. Час ушёл на то, чтобы сузить список до одного файла.
//
// Ошибка не в том, что отладочный файл плохой. Ошибка в том, что он **незаметен**:
// имя начинается с `tests/`, попадает под `tests/**/*.test.js` и молча живёт.
//
// ## Что здесь проверяется
//
// В `tests/` нет файлов с именами, которые означают «я тут временно посчитал».
// Проверка deliberately смотрит на имя, а не на содержимое: содержимое меняется
// каждый час, а имя временности — нет.

import { describe, it, expect } from 'vitest'
import { readdirSync } from 'node:fs'

/**
 * Куски имён, которые означают «отладка, черновик, временно».
 *
 * Важен разделитель ПЕРЕД словом, а не после. Первая версия требовала его с
 * обеих сторон — и файл `dbgD.test.js`, из-за которого прогон не
 * заканчивался, правило не ловило: после `dbg` стояла буква, а не разделитель.
 * Ровно тот случай, ради которого правило и писалось.
 */
const TEMP = /(^|[._-])(dbg|debug|scratch|tmp|temp|wip|sandbox|probe|zzz)/i

describe('В проверках нет временных файлов', () => {
  const files = readdirSync(new URL('.', import.meta.url)).filter((f) => f.endsWith('.test.js'))

  it('список проверок не пуст — иначе проверять нечего', () => {
    expect(files.length, 'в tests/ не нашлось ни одного файла проверок').toBeGreaterThan(50)
  })

  it('ни один файл проверок не назван как отладка', () => {
    const temp = files.filter((f) => TEMP.test(f.replace(/\.test\.js$/, '')))
    expect(temp,
      `во временных файлах: ${temp.join(', ')}. Такой файл попадает в общий прогон, `
      + 'берёт стенд и портит его состояние для следующего файла — так и вышло '
      + 'с `dbgD.test.js`, из-за которого прогон не заканчивался')
      .toEqual([])
  })

  it('проверка про временность сама не попадает под это правило', () => {
    // Иначе правило запрещает само себя и его приходится исключать руками.
    expect(TEMP.test('noTempFiles.test.js'), 'правило запрещает само себя').toBe(false)
    expect(TEMP.test('dbgD.test'), 'а вот это — ровно тот файл, что попал в проект').toBe(true)
    expect(TEMP.test('scratch2.test')).toBe(true)
  })
})
