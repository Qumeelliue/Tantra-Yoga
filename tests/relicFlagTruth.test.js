// ФЛАГ ИЗМЕРЕНИЯ ДОЛЖЕН ДЕЛАТЬ ТО, ЧТО НАЗВАН.
//
// ## Что случилось (и почему это дорого стоило)
//
// `--relics=only:X` читался как «измерить одну реликвию X». На деле стояло:
//
//     forced ? relicChoice.find((r) => r.id === forced) || null : …
//
// То есть `|| null`. Стоило взять X один раз — `find` переставал его находить
// (взятые реликвии не предлагаются), и вместе с X **переставал выдаваться любой
// relics**. Замер «одна копия X» на самом деле измерял «одна копия X и ноль
// остальных».
//
// На этих числах можно было объявить: шесть реликвий из четырнадцати делают
// забег ХУЖЕ, чем отсутствие реликвий (59–65 % против 63 %), и начать «чинить»
// контент, который ни при чём. Почти записал в документы.
//
// Спасло одно: перед правкой спросил, может ли игрок вообще получить шесть
// одинаковых реликвий. Розыгрыш исключает взятые — не может. Значит, замер
// мерил не то, что подразумевал, и вопрос закрылся без правки контента.
//
// ## Четвёртый случай одного класса за сессию
//
// 1. `pickLord`: при принудительном владыке не вызывался розыгрыш — сдвигался
//    весь поток, сравнивались разные забеги.
// 2. Экран тронов вместо финала: искался по слову «Вершина Света», которое есть
//    и на троне.
// 3. `--event-pick` без `--event`: отрок применялся к одному событию из трёх, в
//    остальных молча брался верхний.
// 4. Вот этот: `|| null` вместо `|| relicChoice[0]`.
//
// ## Правило
//
// > **Флаг, который молча делает не то, что назван, хуже отсутствующего флага:**
// > он даёт правдоподобный вывод о несуществующем эффекте. И перед тем, как
// > «чинить» что-то по замеру, спроси: а может ли это вообще произойти в игре?

import { it, expect } from 'vitest'
import { describeSlow } from './helpers/slow.js'
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8')

// Забегов 12, а не 30. Проверке нужно лишь увидеть, что доход реликвий НЕ
// обнулился («больше половины обычного»), а не различить две близкие проходимости.
// Больше забегов — значит дольше процесс, а эти проверки идут параллельно с
// остальными файлами: один прогон упирался в таймаут из-за конкуренции за машину,
// и падал он редко и по другой причине, чем та, которую проверяет.
function runSim(args, runs = 12) {
  return execFileSync('node',
    ['--experimental-loader', './scripts/aliases.mjs', 'scripts/fieldBalance.mjs', String(runs), ...args],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 300000 })
}

/**
 * Реликвии за забег — ТОЛЬКО из своей строки.
 *
 * Первая версия искала регулярным выражением «— N за забег» и с радостью брала
 * строку СЕВЫ: «1094 очков за 6 забегов — 182 за забег». То есть проверка
 * реликвий четыре прогона измеряла севу, и это ни разу не помешало ей быть
 * зелёной. Ровно тот класс, о котором файл написан, — пойман на себе самом.
 */
const relicsPerRun = (out) => {
  const line = out.split('\n').find((l) => /^реликвии \(Slay the Spire/.test(l))
  const m = line && line.match(/— ([\d.]+) за забег/)
  return m ? Number(m[1]) : null
}
const winsOf = (out) => {
  const m = out.match(/побед: (\d+) \((\d+)%\)/)
  return m ? Number(m[2]) : null
}

describeSlow('--relics=only:X измеряет реликвию, а не её отсутствие', () => {
  it('с принудительной реликвией доход реликвий НЕ обнуляется', () => {
    // Главная проверка файла. Если флаг тихо перестаёт выдавать реликвии после
    // первой копии, замер сравнивает «одна копия» с «нулём» — и любой вывод
    // о реликвиях оказывается выдуманным.
    const plain = relicsPerRun(runSim(['--sloppy=0.85', '--seva']))
    const forced = relicsPerRun(runSim(['--sloppy=0.85', '--seva', '--relics=only:pratik']))
    expect(plain, 'замер не печатает число реликвий за забег').not.toBeNull()
    expect(forced, 'замер с принудительной реликвией не печатает число реликвий').not.toBeNull()
    expect(forced, `с --relics=only выдалось ${forced} реликвии за забег вместо ${plain} — `
      + 'флаг измеряет не то, что назван').toBeGreaterThan(plain / 2)
  })

  it('принудительная реликвия не обнуляет и покупки в лавке', () => {
    // Тот же класс, второй источник: лавка тянет из того же списка.
    const out = runSim(['--sloppy=0.85', '--seva', '--relics=only:pratik'])
    const bought = out.match(/куплено (\d+)/)
    expect(bought, 'замер не печатает покупки в лавке').toBeTruthy()
    expect(Number(bought[1]), 'лавка не купила ни одной реликвии — флаг обнулил и её')
      .toBeGreaterThan(0)
  })

  it('`--relics=off` честно обнуляет доход — и это единственный флаг, который должен', () => {
    const off = runSim(['--sloppy=0.85', '--seva', '--relics=off'])
    // В режиме `off` строки со счётчиком нет вовсе — замер печатает прямую
    // оговорку. Значит и проверка должна требовать именно её: иначе «нет строки»
    // и «строка есть, но не сходится» станут одним и тем же.
    expect(relicsPerRun(off), 'при --relics=off счётчик реликвий напечатан — флаг не работает').toBeNull()
    expect(off, 'замер не говорит вслух, что реликвии выключены').toContain('бот их не берёт')
    // Связка «выключил реликвии → выключи лавку» проверяется ИСХОДНИКОМ, а не
    // выводом, и вот почему: при `--relics=off` замер пропускает целиком блок, где
    // печатаются и реликвии, и лавка. То есть в выводе нет ни одной строки, по
    // которой видно состояние лавки, и проверить её поведением здесь нельзя —
    // только на 240 забегах, где разница проходимости и есть 17 пунктов.
    //
    // Значит, честный вариант — прибить связку строкой и признать, что она
    // держится на исходнике, а не на поведении.
    const sim = read('scripts/fieldBalance.mjs')
    const shopLine = sim.split('\n').find((l) => l.includes('const SHOP_RELICS'))
    expect(shopLine, 'в замере нет объявления SHOP_RELICS').toBeTruthy()
    expect(shopLine + ' ' + sim.split('\n').slice(
      sim.split('\n').indexOf(shopLine) + 1, sim.split('\n').indexOf(shopLine) + 3).join(' '),
      '`--relics=off` больше не выключает лавку: из неё приходит около пяти '
      + 'реликвий за забег, и «без реликвий» перестаёт значить «без реликвий»')
      .toMatch(/RELIC_MODE\s*!==\s*'off'/)
    expect(winsOf(off), 'замер с --relics=off не напечатал побед').not.toBeNull()
  })

  it('в коде замера не осталось `|| null` на месте выбора реликвии', () => {
    // Строка, а не поведение: поведение проверяется выше и медленнее, но если
    // кто-то снова напишет `|| null` сюда, тесты поведения это поймают, а эта
    // строка покажет, где именно.
    const sim = read('scripts/fieldBalance.mjs')
    expect(sim, 'принудительная реликвия снова гасит доход реликвий')
      .not.toMatch(/forced \? relicChoice\.find\([^)]*\) \|\| null/)
  })
})

describeSlow('Сравнение реликвий между собой наконец возможно', () => {
  it('одна и та же сборка измеряется одинаково при повторе', () => {
    // Проверка воспроизводимости: если числа прыгают между прогонами, любое
    // сравнение реликвий бессмысленно, и сначала надо чинить воспроизводимость.
    const a = runSim(['--sloppy=0.85', '--seva', '--relics=only:pratik'])
    const b = runSim(['--sloppy=0.85', '--seva', '--relics=only:pratik'])
    expect(winsOf(b), 'два одинаковых замера разошлись — сравнивать нечего').toBe(winsOf(a))
  })

  it('замер признаёт, сколько шагает один забег', () => {
    // Число, которым меряется шум, должно быть известно, а не взят на глаз.
    const sim = read('scripts/fieldBalance.mjs')
    expect(sim, 'замер не печатает число забегов рядом с проходимостью').toMatch(/забегов: \$\{RUNS\} \| побед/)
  })
})