// ФИНАЛ ЗАБЕГА ДОСТИЖИМ — И НА НЁМ ЕСТЬ ЧТО ПОЧИТАТЬ.
//
// ## Зачем этот файл
//
// «Вершина Света» уже была недостижима в этой игре. В `onNext` стояло
// `onNext` только при `nextFloor <= 6`, а ветка финала — при `isLastFloor(floor)`
// (floor ≥ 6). Вместе это всегда ложь: экран, обещанный игроку при старте, не
// открывался НИКОГДА. И ни один тест этого не видел, потому что проверялись
// отдельные функции, а петля — целиком.
//
// Значит, «дойти до финала» нельзя проверять разбором функции. Это проверяется
// ТОЛЬКО прогоном: пройти забег до седьмого владыки настоящими экранами.
//
// ## Что здесь проверяется
//
// 1. Финал ВООБЩЕ открывается. Через семь владык на настоящем стенде.
// 2. На финале есть итоговые числа — забег не заканчивается пустым экраном.
// 3. Эти числа — ВЕСЬ забег, а не последняя комната: «освобождено за забег»
//    должно быть больше нуля даже при забеге, где последняя комната была
//    пустой (ровно тот класс поломки, что был в коде до правки).
//
// ## Чего этот тест НЕ делает
//
// Не проверяет баланс и не играет «хорошо». Он зачищает комнаты напрямую:
// вопрос здесь не «сможет ли стенд победить», а «дойдёт ли петля до конца».

import { describe, it, expect, beforeAll } from 'vitest'

let dom = null
let helper = null
let text = () => ''
let targets = () => []

beforeAll(async () => {
  helper = await import('./helpers/dom.js')
  dom = helper.installDom()
  await import('@webapp/js/main.js')
  targets = () => helper.clickables(dom.root)
  text = () => helper.textOf(dom.root)
})

/** Нажать по классу — карточки дара/нефрита/двери без читаемой подписи. */
const byClass = (re) => {
  const n = targets().find((x) => re.test(String(x.className || '')))
  if (!n) return false
  n.dispatch('click')
  return true
}

/** Нажать кнопку по её тексту — выходы с экранов. */
const byText = (re) => {
  const n = targets().find((x) => re.test(helper.textOf(x)))
  if (!n) return false
  n.dispatch('click')
  return true
}

/**
 * Поле Ума сейчас на экране?
 *
 * ПО КЛАССУ, А НЕ ПО `window.__field`. Объект поля переживает смену экрана:
 * после зачистки комнаты он остаётся жить, пока не начнётся следующая. Первая
 * версия проверяла объект и потому 400 шагов подряд «чистила комнату» на
 * экране дверей — то есть тест сообщал о поломке петли там, где её не было.
 *
 * `.field-left` — левая колонка, которая есть только у боя. Слово «Поле Ума» на
 * экране не годится: оно есть и на экране чакр.
 */
const onFieldScreen = () => !!dom.root.querySelector('.field-left')

/**
 * Финал открыт — ПО КЛАССУ ЭКРАНА, а не по слову.
 *
 * Как это чуть не прошло мимо. Экран тронов говорит «На троне Вершина Света
 * сидит один из трёх». Проверка «дошли ли до Вершины Света» по слову была
 * зелёной на ТРОНОМ — то есть проверяла не то, о чём думала, и рапортовала
 * успех там, где финала ещё не было. Ровно тот класс поломки, который проект
 * уже записывал в правила: слово на экране — не признак экрана.
 */
const onFinaleScreen = () => !!dom.root.querySelector('.win-screen')

/** Зачистить текущую комнату: все оки сняты. */
function clearRoom() {
  const st = globalThis.window.__field
  if (!st) return
  for (const f of st.foes) { f.pacified = true; f.hp = 0 }
  st.pacified += st.foes.length
}

/**
 * Один шаг петли: прокрутить кадры и нажать первое, что на экране.
 *
 * Порядок классов — это порядок экранов забега. Ошибка в нём стоила бы
 * «тест дошёл не туда» вместо настоящей поломки, поэтому порядок записан
 * явно и покрыт комментарием, а не «нажми первую кнопку, которая найдётся».
 */
function step() {
  dom.flushRaf(1)
  if (onFieldScreen()) {
    clearRoom()
    for (let i = 0; i < 40 && onFieldScreen(); i++) {
      dom.flushRaf(1)
      const st = globalThis.window.__field
      if (st?.door) { st.player.x = st.door.x; st.player.y = st.door.y }
    }
    return onFieldScreen() ? 'stuck-room' : 'room'
  }
  // Трон чакры → владыка.
  if (byClass(/lord-card/)) return 'lord'
  // Покой и дары — обе карточки имеют класс boon-card; различать не нужно:
  // в обоих случаях берётся первая, и разницы для петли нет.
  if (byClass(/boon-card/)) return 'boon'
  // Реликвия владыки.
  if (byClass(/\bchoice\b.*\brelic\b/)) return 'relic'
  // Выход с экрана реликвии.
  if (byText(/Идти дальше/)) return 'relicGo'
  // Испытание силы.
  if (byText(/дальше/)) return 'elite'
  // Двери.
  if (byClass(/door-card/)) return 'door'
  // Лавка.
  if (byText(/← уйти/)) return 'shop'
  return 'stop'
}

/**
 * Вход в Поле Ума.
 *
 * ПОРЯДОК ЭКРАНОВ ВЗЯТ ИЗ КОДА: титул → варна (`wsel-card`) → почерк (тоже
 * `wsel-card`) → фонтан и нефрит (`jade-card`) → трон чакры (`lord-card`) → бой.
 * Первая версия жала «нефрит» раньше «варны» и упиралась в фонтан.
 *
 * Перед титулом стоит экран «как играть», и он закрывается отдельно. Поэтому
 * ход здесь не «нажать пять кнопок», а «пока боя нет — нажимай то, что на
 * экране»: список экранов перед боем конечен, и порядок приоритетов важнее
 * количества нажатий.
 */
function enterField(limit = 24) {
  for (let i = 0; i < limit && !globalThis.window.__field; i++) {
    dom.flushRaf(1)
    if (byText(/В путь по миру/)) continue
    if (byClass(/wsel-card/)) continue
    if (byClass(/jade-card/)) continue
    // Экран чакр: список `varna-card`, и клик по незакрытой запускает забег.
    // Закрытые — те же карточки, но с классом `locked` и с обработчиком,
    // который ничего не делает: клик по ним выглядит как «игра не началась».
    {
      const open = targets().find((x) => /varna-card/.test(String(x.className || ''))
        && !/locked/.test(String(x.className || '')))
      if (open) { open.dispatch('click'); continue }
    }
    if (byClass(/lord-card/)) continue
    // Вводная экрана: закрыть и посмотреть, что дальше.
    if (byText(/Понятно|Начать|Далее|Дальше|← /)) continue
    break
  }
}

describe('Финал забега достижим', () => {
  it('через владык доходит до «Вершины Света»', () => {
    enterField()
    expect(globalThis.window.__field, `бой не начался; на экране: ${text().slice(0, 120)}`).toBeTruthy()

    // Забег идёт до финала: 7 владык × (3 комнаты + трон) — с запасом.
    const walked = []
    for (let i = 0; i < 600; i++) {
      const what = step()
      walked.push(what)
      if (onFinaleScreen()) break
    }

    expect(onFinaleScreen(),
      `до финала не дошли за ${walked.length} шагов.\n` +
      `Последние шаги: ${walked.slice(-24).join(' → ')}\n` +
      `Экран: ${text().slice(0, 220)}`).toBe(true)
  })

  it('на финале есть итоговые числа забега', () => {
    // Финал-пустой экран — это тихий обрыв: забег закончился, а игрок не
    // узнал ничего. Итог обязан быть на экране, и он обязан быть ЧИТАЕМЫМ.
    const rows = dom.root.querySelectorAll('.win-row')
    expect(rows.length, `на финале нет ни одной строки итога; экран: ${text().slice(0, 200)}`)
      .toBeGreaterThan(3)
    const keys = rows.map((r) => helper.textOf(r))
    expect(keys.some((k) => /комнат пройдено/.test(k)),
      `в итогах нет пройденных комнат: ${keys.join(' | ')}`).toBe(true)
    expect(keys.some((k) => /освобождено за забег/.test(k)),
      `в итогах нет освобождённых за забег: ${keys.join(' | ')}`).toBe(true)
    // Ни одного «не определено» и «NaN» на экране итога — экран не врёт числами.
    expect(/NaN|undefined/.test(text()),
      `на финале числа-пустышки: ${text().slice(0, 200)}`).toBe(false)
  })

  it('итог считает ВЕСЬ забег, а не последнюю комнату', () => {
    // Раньше экран брал `st.foes` последней комнаты и писал «никого не убито»
    // по ней одной: можно было перебить полпути, а экран всё равно звал
    // финал мирным. Здесь проверяем, что число освобождённых — из сводки
    // забега, то есть больше, чем в последней отдельно зачищенной комнате.
    const rows = dom.root.querySelectorAll('.win-row')
    const line = rows.map((r) => helper.textOf(r)).find((k) => /освобождено за забег/.test(k)) || ''
    const n = Number((line.match(/(\d+)/) || [])[1] || '0')
    // Четыре комнаты на этап минимум, и каждая зачищалась целиком: меньше
    // тридцати освобождённых означает, что считают не всё.
    expect(n, `освобождено за забег: ${n} — считается не весь забег`).toBeGreaterThan(20)
  })
})