// ЭКРАН ВХОДА НЕ ДОЛЖЕН БЫТЬ ИНСТРУКЦИЕЙ.
//
// ## Что случилось
//
// Автор посмотрел на игру и сказал: «каких-то кучу, каких-то пояснений, никто это
// читать не будет». Посчитали: **1120 знаков** до первого нажатия — пять шагов с
// описаниями, из которых один на 326 знаков.
//
// Проверка по коду показала, что каждое из пяти утверждений игра уже говорит в
// момент, когда оно нужно:
//
//   «жми дефлект» → плашка «ЖМИ ДЕФЛЕКТ» висит НА ОКЕ, в окне удара;
//   «рипу не убить» → удар по рипу печатает «рипу не ранится — его сдерживают»;
//   «между комнатами выбор» → экран дверей сам называет, что за каждой дверью;
//   «смерть — перерождение» → экран поражения говорит «знание остаётся»;
//   «ты идёшь сам» → видно по экрану: садхака, ока, никакого стола с картами.
//
// То есть экран входа не учил, а повторял. Теперь на нём две строки.
//
// ## Зачем файл
//
// Правило без проверки — это пожелание. Через месяц текст начнёт расти обратно:
// кто-то добавит «для понятности ещё одну строчку», и это будет выглядеть как
// забота о новичке. Бюджет знаков — единственное, что это останавливает.
//
// ## Что здесь НЕ проверяется
//
// Не проверяется, что подсказки в бою действительно появляются: это делает
// `tests/hints.test.js` на настоящем бою. Здесь только размер.

import { describe, it, expect, beforeAll } from 'vitest'
import { installDom, textOf } from './helpers/dom.js'

/** Бюджет экрана входа. §8.1 правила проекта: одна подсказка — до 60 знаков. */
const BUDGET = 200

let dom
beforeAll(async () => {
  dom = installDom({ fresh: true })
  await import('@webapp/js/main.js')
})

/** Заходим до первого экрана — чтобы увидеть экран входа, а не титул. */
function toOnboarding() {
  for (let i = 0; i < 6; i++) {
    const scr = dom.root.childNodes[dom.root.childNodes.length - 1]
    const t = textOf(scr)
    if (/Понятно — в путь/.test(t)) return t
    const b = [...scr.childNodes].flatMap((n) => [n, ...(n.childNodes || [])])
      .find((n) => /Понятно|Начать/.test(textOf(n)))
    if (b) { b.dispatch('click'); continue }
    break
  }
  const scr = dom.root.childNodes[dom.root.childNodes.length - 1]
  return textOf(scr)
}

describe('Экран входа: две строки, а не инструкция', () => {
  it('весит не больше бюджета', () => {
    const t = toOnboarding()
    expect(/Понятно\s*—\s*в путь/.test(t), `экран входа не открылся; видно: «${t.slice(0, 160)}»`).toBe(true)
    // Кнопка — не инструкция, её текст не считаем.
    const withoutButton = t.replace(/Понятно\s*—\s*в путь\s*▶?/g, '')
    expect(withoutButton.length,
      `на экране входа ${withoutButton.length} знаков при бюджете ${BUDGET}. `
      + `Экран входа не место для инструкций: каждое из этих утверждений игра `
      + `и так говорит в нужный момент. Что именно: «${withoutButton.slice(0, 200)}»`)
      .toBeLessThanOrEqual(BUDGET)
  })

  it('называет, что это за игра', () => {
    const t = toOnboarding()
    // Единственное, чего нет больше нигде: ЧТО это. Как играть — игра сообщает
    // сама и в нужный момент. Правило проекта (§8.1): если правило нельзя
    // показать на предмете, оно не показано; правило про дефлект показать можно,
    // и оно висит на оке.
    expect(t, 'не сказано, что это рогалик — игрок не понимает, во что он попал')
      .toMatch(/рогалик/i)
  })

  it('на экране входа нет повелений — их место в бою', () => {
    // Настоящий запрет, а не «похоже на инструкцию». Повеление — это «жми»,
    // «нажми», «бери», «выбери», «смотри». На экране входа им неуместно: игра
    // говорит их сама и тогда, когда действие доступно.
    const t = toOnboarding().replace(/Понятно\s*—\s*в путь|▶/g, '')
    for (const hit of t.matchAll(/\b(жми|нажми|бери|возьми|выбери|смотри|не бойся|должен)\b/gi)) {
      expect(hit[0], 'на экране входа есть повеление «' + hit[0] + '» — такие вещи говорит '
        + 'игра в момент действия, а не до него').toBe('')
    }
  })

  it('не пересказывает то, что игра говорит сама', () => {
    const t = toOnboarding()
    // Каждая строка ниже уже произносится игрой в момент действия. Если она
    // вернётся на экран входа — значит кто-то решил, что «лучше объяснить
    // заранее», и полоса инструкций снова начала расти.
    const ужеСказано = [
      [/жми\s+дефлект|жми кольцо/i, 'подсказку про дефлект вешает плашка на оке'],
      [/рипу не ран|рипу не убить/i, 'про рипу говорит сам удар в логе боя'],
      [/знание оста|не знание/i, 'что остаётся после смерти, говорит экран поражения'],
      [/нефрит/i, 'про нефрит говорит карточка у Фонтана'],
    ]
    for (const [re, where] of ужеСказано) {
      expect(t, `на экране входа снова есть «${re.source}» — а ${where}. `
        + 'Повторять надо в момент действия, а не до него').not.toMatch(re)
    }
  })
})