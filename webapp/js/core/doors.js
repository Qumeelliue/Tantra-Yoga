// ДВЕРИ — копия из Hades (Supergiant), выбор после комнаты.
//
// Откуда взято. В Hades после каждой комнаты на экране стоят **две–четыре
// двери**, и на каждой **значок того, что внутри**: бой, элита, сокровище,
// лавка, покой, сюжет. Игрок выбирает путь, а не проходит его. Это то, что
// делает забег Hades забегом, а не лестницей: два одинаковых подряд — скучно,
// а выбор между «сейчас подраться» и «зайти в лавку за монетой» — это игра.
//
// У нас Поле Ума шло строго лестницей: комната, комната, комната, владыка.
// Три комнаты подряд одинаковые, выбора нет, и забег читался как повтор.
//
// Что копируется 1:1:
//
//   · **двери показывают, что внутри** — не «выбери событие», а значок и слово;
//   · **выбираешь ты**, и выбор отменяем только смертью;
//   · **дверь владыки на месте всегда** и всегда последняя;
//   · **состав дверей — розыгрыш** (Hades не повторяет один и тот же выбор
//     подряд), и он идёт через переданный `rng`, а не через `Math.random`:
//     иначе забег нельзя воспроизвести, и замер мерил бы другую игру.
//
// ЧЕГО НЕТ И ПОЧЕМУ НЕТ:
//
//   · **элитный бой** (StS elite) и **испытание силы** (Hades Challenge) —
//     сначала не делались: требовали новых чисел врага, а числа поля без слов
//     автора не трогаются. Решение автора 2026-09-30 («делай сам всё»)
//     разрешило: дверь «испытание силы» сделана, числа заданы и **замерены**
//     (МЕХАНИКА 50), а плата — нефрит, то есть та же валюта, что покупает
//     возврат из смерти.
//   · **сокровище/сундук** — отдельного экрана с лутом нет, а пустая дверь
//     враньё. Не делаем.
//
// Правило, которое держит всё остальное: **в списке дверей всегда есть хотя бы
// одна дверь боя.** Иначе игрок, идя по лавкам и покоям, просто не встретит
// оков — и «мирный финал» станет достижимым не умением, а маршрутом. Это было
// бы враньём ровно того же класса, что «убить их нельзя» (МЕХАНИКА 41).

import { ROOMS_PER_STAGE } from './stageRoute.js'

/** Что может быть за дверью. `kind` — команда экрану, остальное — для игрока. */
export const DOOR_KINDS = {
  room: { kind: 'room', icon: '◉', name: 'Оковы', hint: 'Обычная комната: оковы и монеты.' },
  boon: { kind: 'boon', icon: '✦', name: 'Дар', hint: 'Дар без боя. Один из трёх.' },
  shop: { kind: 'shop', icon: '◈', name: 'Лавка', hint: 'Монеты на товар. Бой не будет.' },
  rest: { kind: 'rest', icon: '☾', name: 'Покой', hint: 'Восстановиться или стать крепче.' },
  chaos: { kind: 'chaos', icon: '⚡', name: 'Хаос-путь', hint: 'Дар даром — но в проклятие.' },
  elite: { kind: 'elite', icon: '✵', name: 'Испытание силы', hint: 'Одна злея ока вместо комнаты. Плата — нефрит.' },
  boss: { kind: 'boss', icon: '✹', name: 'Владыка', hint: 'Комната владыки чакры.' },
}

/**
 * Розыгрыш дверей после комнаты.
 *
 * @param {object} p
 * @param {number} p.room номер комнаты этапа, 0-based
 * @param {boolean} p.hasBoss есть ли у этапа владыка
 * @param {function} p.rng генератор — ОБЯЗАТЕЛЕН, иначе падение ниже
 * @param {number} [p.count] сколько обычных дверей (2–3, как в Hades)
 * @returns {Array<{kind:string,icon:string,name:string,hint:string}>}
 */
export function rollDoors({ room, hasBoss, rng, count = 0 } = {}) {
  // Генератор ОБЯЗАТЕЛ, и это не формальность. Если бы двери падали из
  // `Math.random`, замер дверей мерил бы не тот забег, который играется, —
  // ровно та ошибка, что была с `fieldBalance` и его собственным `calmMul`.
  // Падать здесь лучше, чем разойтись с игрой молча.
  if (typeof rng !== 'function') throw new TypeError('rollDoors: нужен rng — двери обязаны повторяться')
  const rand = rng
  const n = Number.isFinite(room) ? room : 0

  // Дверь владыки — на месте всегда и всегда последняя. В Hades босс всегда
  // виден: игрок знает, что он идёт к нему, и выбирает дорогу САМ.
  const bossDue = !!hasBoss && n + 1 >= ROOMS_PER_STAGE
  const doors = []
  if (bossDue) doors.push({ ...DOOR_KINDS.boss })

  // Пул обычных дверей. Без повторов: два одинаковых значка рядом читаются
  // как ошибка, а не как выбор.
  const pool = [DOOR_KINDS.room, DOOR_KINDS.boon, DOOR_KINDS.shop, DOOR_KINDS.rest,
    DOOR_KINDS.chaos, DOOR_KINDS.elite]
  const want = count > 0 ? count : (rand() < 0.5 ? 2 : 3)

  const chosen = [DOOR_KINDS.room]                 // правило: бой есть всегда
  while (chosen.length < want && pool.length) {
    const k = Math.floor(rand() * pool.length) % pool.length
    const cand = pool.splice(k, 1)[0]
    if (!chosen.some((c) => c.kind === cand.kind)) chosen.push(cand)
  }

  // Дверь боя — первая и всегда заметная: она и есть «дальше идти в оковы»,
  // остальные — отступления от прямого пути. Так же в Hades: значок боя на
  // двери читается первым.
  const rest = chosen.filter((c) => c.kind !== 'room')
  const out = [DOOR_KINDS.room, ...rest]
  // Дверь владыки в конце: до него идут, а не мимо него.
  return bossDue ? [...out, DOOR_KINDS.boss] : out
}

/** Есть ли среди дверей дверь боя — правило «бой есть всегда». */
export function hasCombatDoor(doors) {
  return (doors || []).some((d) => d.kind === 'room')
}