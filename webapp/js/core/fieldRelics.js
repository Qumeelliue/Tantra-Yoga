/**
 * РЕЛИКВИИ В ПОЛЕ УМА — копия слотов Slay the Spire.
 *
 * ## Почему это здесь, а не выдумка
 *
 * В Slay the Spire реликвия — **двигатель разнообразия забега**: после каждого
 * босса ты выбираешь одну из трёх, она действует до конца забега, и именно
 * набор решений делает два забега непохожими. Это не «красивость» и не
 * украшение: без этого слота два забега отличаются только тем, какие 14 даров
 * выпало.
 *
 * Проверено, чего не хватало. В Поле Ума за забег у игрока было **восемь
 * решений**: один нефрит и семь даров. Забег — 25 комнат. Это тонко для
 * рогалика, где забег длится десять минут.
 *
 * Контент уже был написан и не выдуман: 14 реликвий с подлинными терминами
 * Ананда Марги (Пратик, Триданда, Шанкха, Камбала, Махамантра-мала,
 * Шива-лингам, Калачакра, Туласи, Прана-дроп, Гуру-даршана, Дхрувасмрити,
 * Джатисмара, Шоча-майнджуса, Каупиина), каждая с цитатой и источником.
 * Работали они только в карточном пути. Здесь они работают в Поле Ума.
 *
 * ## Почему описания свои, а не карточные
 *
 * Описания из `content/relics.json` написаны для карточного пути: «Ахимса-карты
 * дают +1 успокоение», «карты мантр стоят на 1 севу дешевле», «в начале каждого
 * боя садхака получает +1 силу». В Поле Ума нет карт, нет Праны и нет отдельного
 * «боя» — есть комната, мантра и возврат удара. Взять описание из карточки значит
 * **оставить на экране текст, которого нет в игре** (МЕХАНИКА 41: обещание,
 * которого не выполняет код). Поэтому у каждой реликвии своё поле `fieldDesc` —
 * правдивое про Поле Ума, — и проверка сверяет именно его.
 */

import { RELICS } from './data.js'

/**
 * Как действие реликвии переводится в опцию боя Поля Ума.
 *
 * `BRIDGE` — мост между двумя играми. Он назван явно, потому что именно здесь
 * легче всего выдумать механику: слева «карта мантры», справа «возврат удара».
 * Каждый переход записан здесь целиком, чтобы пересматривать его можно было в
 * одном месте, а не разбросанным по бою.
 */
const BRIDGE = {
  // В Поле Ума спокойствие даёт ВОЗВРАЩЁННЫЙ УДАР, а не карта.
  mod_pacify: (o, amt) => { o.deflectCalm += amt },
  // Мантры, а не практики: одна трата Ци, а не набор карт.
  mod_practice_cost: (o, amt) => { o.mantraCostCut -= amt },
  // Снятая ока даёт саттву — единственный источник в Поле Ума.
  mod_pacify_sattva: (o, amt) => { o.sattvaPerPacify += amt },
  // Серия дефлектов, а не колода: сколько живёт цепочка.
  mod_kiirtana_draw: (o, amt) => { o.comboWindow += amt * 0.8 },
  // Перекос гун на входе, а не «карта при розыгрыше».
  //
  // Порядок параметров: `(o, amt, fx, id)`. Первая версия объявила здесь
  // `(o, fx)` — и `fx.s` читался из числа, то есть всегда был `undefined`.
  // Две реликвии (Шива-лингам, Каупиина) выпадали и НИЧЕГО НЕ ДЕЛАЛИ, а
  // проверка на «меняет ли опцию» нашла это сама, через неделю правки.
  mod_guna_start: (o, amt, fx) => { o.gunaStartS += (fx && fx.s) || 0 },
  // Ока входит в комнату спокойнее — то есть ей нужно МЕНЬШЕ дефлектов.
  //
  // Знак проверен замером. Данные говорят `amount: -1` («враг стартует с −1
  // силой»), то есть ока слабее. Первая версия писала `o.foeCalmBonus -= amt`, и
  // при `amt = -1` получалось `+= 1`: ока становилась ТРУДНЕЕ, ровно наоборот
  // обещанного. Замер поймал это один — 42 % побед против 58 % базы, и
  // «Калачакра» была единственной реликвией ниже базы на два забега.
  mod_enemy_start_strength: (o, amt) => { o.foeCalmBonus += amt },
  // Каждая комната, а не первый бой.
  mod_combat_start_heal: (o, amt) => { o.roomStartHeal += amt },
  mod_combat_start_block: (o, amt) => { o.roomStartShield += amt },
  // Число на карточке — «−1 сила», и оно обязано означать «слабее». Знак
  // проверяется тестом на деле, а не комментарием: если реликвия обещает
  // облегчить, а замер говорит, что с ней бой тяжелее, — это враньё.
  // Знание, а не сила: видно, сколько спокойствия оке нужно.
  mod_peek_start: (o) => { o.telegraphPeek = 1 },
  // Садхака входит в комнату с запасом Ци.
  mod_player_start_strength: (o, amt) => { o.psychicStart += amt * 2 },
  // Два предмета на одну величину — как в Spire, где урон и длительность
  // «слабости» разные ручки. `mod_tamas_imbalance` в карточном пути один, а
  // здесь он раскладывается по разным предметам: «Туласи» ослабляет вдвое,
  // «Камбала» снимает вовсе.
  mod_tamas_imbalance: (o, amt, fx, id) => {
    o.weakPenaltyMul = id === 'kambala' ? 0 : (o.weakPenaltyMul ?? 1) * 0.5
  },
}

/** Слотов, для которых в Поле Ума нет величины. Проверяется тестом. */
export const UNSUPPORTED = []

/**
 * Применить набор реликвий к опциям боя.
 *
 * @param {object} base опции забега (уже с даром, нефритом, жаром)
 * @param {string[]} owned id реликвий
 * @returns {object} новый набор опций — исходный не меняется
 */
export function applyFieldRelics(base, owned = [], defs = RELICS) {
  const o = { ...base }
  if (!owned || !owned.length) return o
  for (const id of owned) {
    const def = defs[id]
    if (!def) continue
    for (const fx of def.effects || []) {
      const fn = BRIDGE[fx.kind]
      if (!fn) { UNSUPPORTED.push(`${id}:${fx.kind}`); continue }
      fn(o, fx.amount || 0, fx, id)
    }
  }
  // Та же страховка, что в `applyBoons`: одно «пропавшее» поле превращается в
  // NaN, и NaN тихо портит весь бой — вместо того чтобы просто не сработать.
  for (const k of Object.keys(o)) {
    const v = o[k]
    if (typeof v === 'number' && !Number.isFinite(v)) {
      o[k] = typeof base[k] === 'number' ? base[k] : 0
    }
  }
  if (o.mantraCostCut < 0) o.mantraCostCut = 0   // мантра не может стоить 0 и меньше
  if (o.psychicStart > o.psychicMax) o.psychicStart = o.psychicMax
  return o
}

/**
 * Три реликвии на выбор из тех, которых ещё нет.
 *
 * Почему без редкости: в Slay the Spire редкость весит выбор (шанс выпадения),
 * и поле зрения игрока читает список целиком. Здесь список из трёх показывается
 * целиком же, и весить его нечем — а выдумывать вес значит выдумывать правило.
 *
 * @param {object} p
 * @param {function} p.rng генератор — обязателен, иначе замер считает не тот забег
 * @param {string[]} [p.owned] уже взятые
 * @param {number} [p.n] сколько предъявить
 */
export function rollFieldRelics({ rng, owned = [], n = 3, defs = RELICS } = {}) {
  if (typeof rng !== 'function') throw new TypeError('rollFieldRelics: нужен rng — иначе замер меряет не тот забег')
  const pool = Object.keys(defs).filter((id) => !owned.includes(id))
  const out = []
  const left = pool.slice()
  while (out.length < Math.min(n, left.length)) {
    out.push(left.splice(Math.floor(rng() * left.length), 1)[0])
  }
  return out.map((id) => fieldRelicView(id, defs))
}

/** Реликвия глазами Поля Ума: имя, честное описание, цитата. */
export function fieldRelicView(id, defs = RELICS) {
  const def = defs[id]
  if (!def) return null
  const cite = def.quoteId
  return {
    id,
    name: def.name,
    sanskrit: def.sanskrit || '',
    rarity: def.rarity || 'common',
    // Описание для Поля Ума. Карточное не годится: там карты, Прана и «бой».
    desc: FIELD_DESC[id] || def.desc,
    fieldDesc: FIELD_DESC[id] || '',
    quoteId: cite,
  }
}

