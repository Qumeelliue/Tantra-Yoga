// СОБЫТИЕ — экран без боя, где выбирают с названной платой (Slay the Spire, Events).
//
// ## Откуда взято
//
// В Slay the Spire событие — не отдельная механика, а **вид двери**: дверь
// «?», за ней экран без боя, внутри две-три строки с вариантами и у каждого
// названная плата. Исход один, но получить можно разное, и платить — разное.
// Это то, чего у нас не было вообще: все 25.8 решений за забег были одного вида
// («возьми один предмет, платы нет»).
//
// ## Почему дверь, а не отдельный экран
//
// Дверь уже подписана, игрок уже выбирает путь, и лимит «одна небоевая дверь на
// этап» уже существует. Событие **занимает это место**, а не добавляется сверху:
// иначе «не драться» стало бы выгоднее и мирный финал — маршрутом, а не
// умением (то же, что уже было сделано с дверьми, см. `doors.js`).
//
// ## ГЛАВНОЕ ПРАВИЛО ФАЙЛА: ТЕКСТ НА КАРТОЧКЕ НЕ ПИШЕТСЯ РУКАМИ
//
// У каждого выбора есть `effects` — список величин, которые действительно
// применяются. Надпись на кнопке **выводится из этого списка** функцией
// `effectText`. Значит, обещание на карточке и поведение кода — это одно и то же
// место: разойтись они не могут физически.
//
// Раньше в этом проекте было наоборот: карточка обещала одно, а код делал другое
// (МЕХАНИКА 41), и это повторялось четыре раза за две сессии.
//
// ## Термины
//
// Только из уже сверенного корпуса `content/quotes.json` и `content/boons.json`:
// **сева**, **тапас**, **апариграха**. События на термины «каруна» и «сатья»
// были написаны и УБРАНЫ: на каруну в корпусе нет цитаты, а правило проекта
// запрещает выдумывать термин. Лучше три события с проверяемым источником, чем
// четыре, из которых одно держится на моей памяти.
//
// Три, а не четыре — ещё и потому, что дверь события выпадает примерно один-два
// раза за забег: три события уже дают разнообразие внутри побега. Добавлять
// контент дальше только если замер покажет, что узкое место — в нём.

