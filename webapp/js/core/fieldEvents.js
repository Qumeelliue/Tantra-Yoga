/**
 * Человеческие названия величин — единственное место, где живут слова.
 *
 * ЗНАК ВСЕГДА ПЕЧАТАЕТСЯ, в том числе для расхода. Первая версия писала
 * ``n > 0 ? `+${n} севы` : `${-n} севы` `` — и карточка «отдать зерно» обещала
 * «3 севы», хотя игрок их ОТДАВАЛ. Это ровно тот класс поломки, который в этой
 * игре повторялся четыре раза: экран обещает одно, игрок получает другое. Поймано
 * тестом `fieldEvents.test.js` при первом же запуске.
 */
const signed = (n, noun) => `${n > 0 ? '+' : (n < 0 ? '−' : '')}${Math.abs(n)} ${noun}`

const KIND_TEXT = {
  seva: (n) => signed(n, 'севы'),
  coins: (n) => signed(n, 'монет'),
  heal: (n) => signed(n, 'жизни'),
  shield: (n) => `щит ${n} в следующих комнатах`,
  boon: () => 'дар из трёх',
  chaos: () => 'урон вдвое до конца забега',
}

/**
 * Подпись под кнопкой — ИЗ ЭФФЕКТОВ, а не из рукописного текста.
 *
 * Пустые эффекты — это «ничего не получаешь», и это тоже надо написать: иначе
 * кнопка «Пройти мимо» выглядит поломанной, хотя так и задумано.
 */
export function effectText(effects) {
  const list = effects || []
  if (!list.length) return 'ничего не получаешь и ничего не отдаёшь'
  return list.map((e) => {
    const fn = KIND_TEXT[e.kind]
    if (!fn) return ''
    const n = Number.isFinite(e.amount) ? e.amount : 1
    return fn(n, e)
  }).filter(Boolean).join(' · ')
}


/**
 * Розыгрыш события.
 *
 * `rng` ОБЯЗАТЕЛЕН, как и в дверях: событие из `Math.random` нельзя
 * воспроизвести, и замер событий мерил бы не ту игру, в которую играют.
 *
 * `seen` — события, которые уже были в этом забеге. Если осталось одно, а оно
 * уже было — отдаём последнее: лучше повтор, чем дверь, на которой ничего нет.
 */
export function rollFieldEvent({ rng, seen = [] } = {}) {
  if (typeof rng !== 'function') throw new TypeError('rollFieldEvent: нужен rng — событие обязано повторяться')
  const pool = FIELD_EVENTS.filter((e) => !seen.includes(e.id))
  const list = pool.length ? pool : FIELD_EVENTS
  return list[Math.floor(rng() * list.length) % list.length]
}

/**
 * ЧТО ПРОИЗОЙДЁТ — чистое чтение эффектов.
 *
 * Возвращает сводку величин для проверки и для экрана. Ничего не применяет:
 * применение живёт в игре и в тесте вызывается отдельно, чтобы проверка
 * «обещание = поведение» сравнивала одно с другим, а не одно с собой.
 */
export function previewEffects(effects) {
  const out = { seva: 0, coins: 0, heal: 0, shield: 0, chaos: false, boon: false, boonId: null }
  for (const e of effects || []) {
    if (e.kind === 'boon') { out.boon = true; out.boonId = e.id || null }
    else if (e.kind === 'chaos') out.chaos = true
    else if (typeof out[e.kind] === 'number') out[e.kind] += Number.isFinite(e.amount) ? e.amount : 0
  }
  return out
}

/** Проверка: у события есть текст, и у каждого выбора — подпись и эффекты. */
export function eventDefects(events = FIELD_EVENTS) {
  const bad = []
  for (const e of events) {
    if (!e.id || !e.title || !e.text) bad.push(`${e.id}: нет id/заголовка/текста`)
    if (!e.choices?.length) bad.push(`${e.id}: ни одного выбора`)
    for (const c of e.choices || []) {
      if (!c.label) bad.push(`${e.id}/${c.id}: у выбора нет названия`)
      if (!effectText(c.effects)) bad.push(`${e.id}/${c.id}: подпись не выводится — игрок не видит платы`)
    }
  }
  return bad
}