/**
 * ПИЩА ДЛЯ МЕНТАЛЬНОСТЕЙ В ПОЛЕ УМА (Human Society Part 2, §12).
 *
 * Копия того, что уже было в карточном пути, — те же четыре ментальности и те
 * же поступки. В Поле Ума эти поступки выглядят иначе, чем в колоде, поэтому и
 * пища названа заново:
 *
 *   · **Смелость** (освобождение не проходит даром) — за чакру, в которой
 *     что-то сняли. Ровно как в колоде, где победа с успокоением кормит
 *     кшатрию. Чакра без единого удара платит вдвое: освобождение с кровью и
 *     освобождение без неё — не одно и то же.
 *   · **Различение** (знание открывает) — за оки, чей смысл ты УЗНАЛ в этой
 *     чакре. Не чаще двух за чакру: третье око подряд — уже не знание, а сбор
 *     урожая.
 *   · **Присутствие** (труд над умом) — за чакру, в которой была сева. Не чаще
 *     двух за чакру, иначе присутствие росло бы вдвое быстрее прочих, а рост
 *     должен быть ПАРАЛЛЕЛЬНЫМ: четыре ментальности развиваются вместе, и
 *     отстающая тянет остальных вниз.
 *   · **Мудрость** (осознанная трата, а не накопление) — за вложенное в лавке
 *     Поля Ума. Начисляется сразу при покупке, потому что там некуда ждать
 *     конца чакры.
 *
 * ## Почему файл отдельный, а не функция в `main.js`
 *
 * Тест должен проверять ПРАВИЛО ИГРЫ, а не его пересказ. Пока правило жило
 * внутри `main.js`, проверка вынуждена была повторить его у себя — и
 * `tests/varnaGrowth.test.js` повторил СТАРУЮ версию: очки за комнату, без
 * потолка. Игра давно считает раз за чакру, а тест был зелёный и проверял
 * копию мёртвого правила (МЕХАНИКА 43 в тестах: «покрыто», а не измерено).
 *
 * Правило вынесено, чтобы игра и проверка читали одну функцию. Дальше менять
 * пороги — здесь, и проверка упадёт сама.
 *
 * @param {{varnaPacifiedRooms?:number, varnaBloodlessRooms?:number,
 *          varnaServedRooms?:number, varnaLearned?:number}} run
 * @returns {Array<[string, number]>} — что начислить: [ментальность, очки]
 */
export function floorVarnaFood(run) {
  const out = []
  if ((run?.varnaPacifiedRooms || 0) > 0) {
    // Чистая чакра стоит вдвое больше. Считается по ЧАКРЕ, а не по комнате:
    // четыре чистые комнаты подряд — это одна чистая чакра, а не четыре.
    const clean = (run.varnaBloodlessRooms || 0) >= run.varnaPacifiedRooms
    out.push(['kshatriya', clean ? 2 : 1])
  }
  const learned = Math.min(run?.varnaLearned || 0, 2)
  if (learned) out.push(['vipra', learned])
  const served = Math.min(run?.varnaServedRooms || 0, 2)
  if (served) out.push(['shudra', served])
  return out
}
