// ЕЖЕДНЕВНЫЙ ЗАБЕГ — копия из Dead Cells, Slay the Spire и Duolingo.
//
// У нас уже был «ежедневный вызов», но это **счётчик заданий** (Duolingo):
// «успокой 2 врагов», «достигни самадхи». Это полезно и не работает как вызов.
//
// Чего не хватало. В Dead Cells Daily Challenge — это не задание, а **один и тот
// же путь для всех**: конкретные семена, конкретные комнаты, конкретная
// сложность. Игрок не «собирает два освобождения», он **проходит одну и ту же
// локацию** и сравнивает с миром, а не с собой.
//
// Три игры — три части механики, все копируются:
//
//   · **Dead Cells** — одинаковый путь по дате, у всех один;
//   · **Slay the Spire** — ежедневное seed-разнообразие вместо честной нагрузки;
//   · **Duolingo** — «одна попытка в день»: нельзя набить, возвращаешься
//     завтра.
//
// Отличие и зачем. Наш ежедневный забег **бесплатный и дополнительный**: он не
// отнимает жар и не ломает обычный. Причина простая — в Telegram Mini App не
// существует «обязательно сыграй сегодня», и требовать этого нельзя, а обещать
// награду за вход, которая ничего не стоит, — обман. Поэтому ежедневный забег
// даёт **то, чего не даёт обычный: честный один и тот же путь**.
//
// Правило: **один путь на всех обязан получаться из даты, а не из случайности
// игрока.** Иначе это не ежедневный вызов, а «сегодня у меня выпало трудно».

import { mulberry32 } from './engine.js'

/**
 * Seed дня. Один и тот же у всех, кто зашёл сегодня.
 *
 * Считается из даты, а не из «сейчас минус тогда»: игрок может войти в любой
 * момент суток и обязан получить один и тот же путь.
 */
export function dailySeed(dayKey) {
  let h = 2166136261
  const s = String(dayKey || '')
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  // Приводим к положительное 32-битное — иначе `mulberry32` получит
  // отрицательное состояние, и результат станет зависимым от знака.
  return h >>> 0
}

/**
 * Розыгрыш ежедневного забега.
 *
 * Генератор ТОТ ЖЕ, что у игры (`engine.js: mulberry32`), а не похожий: два
 * разных генератора означают, что «честный» замер и «честный» ежедневный
 * забег — разные игры, и сравнивать их нельзя. Первая версия этого модуля
 * копировала алгоритм построчно — и это было бы то же самое, только
 * незаметно.
 */
export function dailyRng(dayKey) {
  return mulberry32(dailySeed(dayKey))
}

/**
 * Нужно ли предлагать ежедневный забег.
 *
 * Одно условие и одно «уже сегодня». Всё.
 * @returns {{on:boolean, dayKey:string, done:boolean}}
 */
export function dailyOffer(meta, todayKey) {
  const d = meta?.daily || {}
  const key = String(todayKey || '')
  return {
    on: !!key && d.date === key,
    dayKey: key,
    // Отдельный флаг: `done` у вызова-задания не означает, что ежедневный
    // забег сыгран. Одно другого не заменяет — иначе игрок выполнил задание и
    // решил, что день закрыт.
    done: !!d.dailyRunDone && d.dailyRunDate === key,
  }
}

/** Ежедневный забег сыгран — помечаем один раз в день. */
export function markDailyRunPlayed(meta, dayKey) {
  if (!meta) return
  meta.daily = { ...(meta.daily || {}), dailyRunDate: dayKey, dailyRunDone: true }
}
