// ЖАР — добровольная сложность, которая сама себя оплачивает.
//
// Скопировано 1:1 из **Hades** (Supergiant), механика «Heat»:
//
//   · список предъявляемых условий, каждое добавляет +1 к жару;
//   · игрок САМ выбирает уровень ДО забега — это не наказание, а ставка;
//   · чем выше жар, тем больше награды за прохождение.
//
// Отличие от Hades и почему так: у них жар — это перебор параметров врага
// («враги бьют на 30 % сильнее», «у тебя меньше здоровья»). Это перебор, а не
// механика. У нас жар — **смещение гун**, то есть ровно то, что игра уже
// умеет: чем дальше заходишь, тем хуже равновесие. §8.3 уже описывает, что
// делает перекос. То есть мы НЕ вводим нового правила — мы включаем
// существующее раньше и сильнее.
//
// Почему это вообще нужно. Без жара у игры нет причины начинать забег второй
// раз: прошёл 7 чакр — всё, повторять незачем. Жар отвечает на вопрос «зачем
// играть снова» честно и без выдумок: **потому что можно взять планку выше**.
// Именно это держит интерес после прохождения в Hades и Dead Cells, а не
// новый контент.
//
// Запись: `design/BASE-GAME.md`, МЕХАНИКА 42.

// ── ЧИСЛА УСЛОВИЙ ────────────────────────────────────────────────────────
// Объявлены ПЕРЕД `HEAT_TIERS`, потому что используются в нём. В первой
// версии стояли литералы, а константы — отдельно и ниже: два источника
// правды, и любая правка числа разъезжалась бы с подписью в интерфейсе.

/** Ступень 1: сдвиг раджаса за ступень. */
export const HEAT_START_R = 1
/** Ступень 2: на сколько медленнее копится спокойствие. */
export const HEAT_CALM_CUT = 0.33
/** Ступень 3: во сколько раз быстрее идут часы смерти. */
export const HEAT_CLOCK_MULT = 1.2
/** Ступень 4: на сколько ниже потолок щита. */
export const HEAT_SHIELD_CUT = 0.3
/** Ступень 5: во сколько раз быстрее растёт авидья. */
export const HEAT_AVIDYA_MULT = 1.25

/**
 * Гуны на старте забега. Раньше стояли в коде поля захардкоженно
 * (`guna: { s: 4, r: 2, t: 3 }`) — то есть перекос нельзя было задать извне,
 * и жар не мог на него подействовать. Значение оставлено тем же, чтобы жар на
 * нуле не менял игру ни на единую единицу.
 */
export const HEAT_GUNA_START = { s: 4, r: 2, t: 3 }

/** Награда за каждую ступень жара: +50 % севы, +35 % очков. */
export const HEAT_REWARD_SEVA = 0.5
export const HEAT_REWARD_SCORE = 0.35

/** Ступени жара. Каждая — одно предъявленное условие, как в Hades. */
export const HEAT_TIERS = [
  {
    id: 'h1',
    name: 'Раджас кренится',
    desc: 'Ум с самого начала кренится в раджас.',
    // Слот читается в `field.js`: `guna: o.gunaStart`. До этой правки гуны
    // были ЗАХАРДКОЖЕНЫ (`{s:4, r:2, t:3}`), и жар на них бы не подействовал.
    //
    // Здесь была своя арифметическая ошибка: счётчик `o.heat` сначала
    // увеличивался, потом считалось `HEAT_START_R * (o.heat - 1)` — на первой
    // ступени это давало ноль, то есть сдвига не происходило ВООБЩЕ, хотя
    // ступень отображалась и обещала награду. Поймал тест на достижимости
    // сдвига. Счётчик нужен для показа, а не для арифметики.
    apply: (o) => {
      o.heat = (o.heat || 0) + 1
      const g = { ...(o.gunaStart || HEAT_GUNA_START) }
      g.r += HEAT_START_R
      o.gunaStart = g
    },
  },
  {
    id: 'h2',
    name: 'Тяжелее терпеть',
    desc: 'Спокойствие копится на треть медленнее.',
    apply: (o) => { o.heat = (o.heat || 0) + 1; o.deflectCalm = Math.round(o.deflectCalm * (1 - HEAT_CALM_CUT) * 1000) / 1000 },
  },
  {
    id: 'h3',
    name: 'Оки злее',
    desc: 'Часы смерти идут быстрее.',
    apply: (o) => { o.heat = (o.heat || 0) + 1; o.clockRamp = Math.round((o.clockRamp || 1) * HEAT_CLOCK_MULT * 1000) / 1000 },
  },
  {
    id: 'h4',
    name: 'Щит короче',
    desc: 'Потолок щита ниже: держать удар в серии больше не выйдет.',
    // Первая версия этого условия была «Никакой севы» (`sevaShield = 0`) —
    // и она была МЁРТВОЙ: `sevaShield` по умолчанию УЖЕ равен нулю, так что
    // ступени 3 и 4 давали одно и то же. Поймал тест на попарной различности
    // ступеней. Условие обязано менять величину, которая сейчас ненулевая,
    // иначе это ярлык без последствий.
    apply: (o) => { o.heat = (o.heat || 0) + 1; o.shieldMax = Math.round(o.shieldMax * (1 - HEAT_SHIELD_CUT)) },
  },
  {
    id: 'h5',
    name: 'Тьма смотрит',
    desc: 'Авидья растёт быстрее.',
    apply: (o) => { o.heat = (o.heat || 0) + 1; o.avidyaGain = Math.round((o.avidyaGain ?? 1) * HEAT_AVIDYA_MULT * 1000) / 1000 },
  },
]

/** Предел на старте: пять ступеней. Расширять только после замера. */
export const HEAT_MAX = HEAT_TIERS.length

/**
 * Применить выбранный жар к набору опций боя.
 *
 * @param {object} o набор опций (тот же, что идёт в `createField`)
 * @param {number} level сколько ступеней выбрано, 0..HEAT_MAX
 * @returns {{level:number, names:string[], shift:number}} что применилось
 */
export function applyHeat(o, level) {
  const lv = Math.max(0, Math.min(HEAT_MAX, Math.floor(level || 0)))
  const names = []
  for (let i = 0; i < lv; i++) {
    HEAT_TIERS[i].apply(o)
    names.push(HEAT_TIERS[i].name)
  }
  o.heat = lv
  return { level: lv, names, shift: o.gunaStartShift || 0 }
}

/**
 * Множитель награды.
 *
 * Одна функция на всё — иначе сева и очки разъедутся при правке.
 * @param {number} level выбранный жар
 * @param {number} base базовое число
 * @param {number} [per] прибавка за ступень (по умолчанию сева)
 */
export function heatReward(level, base, per = HEAT_REWARD_SEVA) {
  const lv = Math.max(0, Math.min(HEAT_MAX, Math.floor(level || 0)))
  return Math.round(base * (1 + lv * per) * 100) / 100
}
