// ПОВЕДЕНИЕ ОК — «у каждого типа врага свой набор приёмов» (Hades).
//
// Раньше все оки вели себя одинаково: подошёл → замахнулся → ударил. Различались
// только цифры. В Hades это главный источник интереса в бою: ты учишься
// читать каждого врага, и одна комната оказывается сложнее другой из-за
// СОСТАВА, а не из-за чисел.
//
// Ничего не выдумано. Поведение каждой оки уже записано в `fieldBuild.js`
// в поле `note` — из источников. Здесь эти записи превращаются в механику:
//
//   «гнев: быстр и слеп»      → короткий замах, злой после дефлекта
//   «жадность: копит и не отступает» → длинная пауза, но замах частый
//   «влечение: тянет к себе»  → во время замаха тянет садхаку к оке
//   «гордость: стоит и смотрит» → не подходит, бьёт с места
//   «зависть: ворует силы»   → отнимает духовную силу
//   «сон: замедляет и усыпляет» → после удара movement замедлен
//   «страх: наводит ужас»    → длинный замах, но достаёт издалека
//   «стыд: прячет и отнимает» → отступает, когда ты подходишь
//   «ненависть: жжёт»        → оставляет ожог (урон со временем)
//   «сомнение: подрывает»    → вселяет «слабость» (слот Slay the Spire)
//   «родовитость: щит и выпад» → копит стойкость, бьёт с места
//   «холодность: стена»      → гасит возврат удара, как стойкость владыки
//   «тщеславие: блеф»        → часть замахов обрывается без удара
//   «злословие: шепчет»      → усиливает неведение

