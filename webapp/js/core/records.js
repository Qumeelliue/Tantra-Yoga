// РЕКОРДЫ — копия из Dead Cells и Slay the Spire.
//
// Зачем. Жар (BASE-GAME 42) отвечает на вопрос «зачем начать забег сильнее».
// Рекорд отвечает на второй вопрос: «зачем пройти его быстрее». Без второго
// вопроса жар — единственная причина повторять, а одной причины мало: игрок
// упирается в потолок однажды и всё.
//
// Что копируется 1:1:
//
//   · **Dead Cells** — «best time» на каждый уровень: рекорд ПРИВЯЗАН к месту,
//     а не к забегу целиком. Игрок соревнуется с собой на одной чакре;
//   · **Slay the Spire** — лучший результат виден сразу на экране статистики,
//     а не спрятан в глубине меню.
//
// Чем отличаемся. У них рекорд — это время: «уложился в минуту». У нас это
// была бы бессмысленная цифра, потому что забег длится 15–30 минут, а время
// зависит от того, сколько раз игрок смотрел в экран. Значит мера у нас —
// **сколько владык снято и сколько оков освобождено за забег**: это зависит от
// умения, а не от скорости пальцев. Рекорд здесь — «самая длинная освобождённая
// цепочка», а не «самое быстрое прохождение».
//
// Правило: **рекорд обязан показываться там, где игрок принимает решение
// входить в забег.** Иначе он не мотивирует, а просто существует. Поэтому
// запись хранится рядом с жаром: оба отвечают на вопрос «зачем ещё раз».

/** Ключ рекорда: седьмой владыке. */
const BEST_KEY = 'best'

/**
 * Учесть забег в рекорде. Возвращает, что изменилось.
 *
 * Считается ТОЛЬКО победа: забег, в котором игрок умер, рекордом не является.
 * Иначе «рекорд» начнёт показывать худшие забеги — то есть мера перестанет
 * мерить мастерство.
 *
 * @param {object} meta
 * @param {{bosses:number, pacified:number, kills:number, time:number}} run
 * @returns {{isRecord:boolean, prev:object|null, now:object}}
 */
export function recordRun(meta, run) {
  if (!meta || !run) return { isRecord: false, prev: null, now: run }
  // Смерть и «оставил забег» рекордом не бывают: мера мастерства, а не
  // переживания.
  if (run.result !== 'victory') return { isRecord: false, prev: null, now: run }
  const now = {
    bosses: run.bosses || 0,
    pacified: run.pacified || 0,
    kills: run.kills || 0,
    time: Math.round(run.time || 0),
    // Возвраты из смерти (Nine Sols: Revival, МЕХАНИКА 49). Рекорд без них
    // и рекорд с ними — РАЗНЫЕ забеги по difficulty, и молча сравнивать их
    // нельзя: игрок покупал нефрит за жизнь и получал рекорд «в обход»
    // собственной смертности.
    revivals: run.revivals || 0,
  }
  const prev = (meta.records && meta.records[BEST_KEY]) || null
  if (!prev) {
    meta.records = { ...(meta.records || {}), [BEST_KEY]: now }
    return { isRecord: true, prev: null, now }
  }
  // Что считать мастерством: больше освобождённых оков, при равенстве —
  // меньше крови. Время НЕ сравнивается: см. шапку модуля.
  //
  // Возвраты не «улучшают» забег и не «ухудшают»: они просто названы. Иначе
  // забег с возвратом вытеснял бы забег без него при тех же оках, а это была
  // бы мера удачи, а не мастерства.
  const better = now.pacified > prev.pacified
    || (now.pacified === prev.pacified && now.kills < prev.kills)
  if (!better) return { isRecord: false, prev, now }
  meta.records = { ...(meta.records || {}), [BEST_KEY]: now }
  return { isRecord: true, prev, now }
}

/** Рекорд для показа. `null`, если рекордов ещё нет. */
export function bestRecord(meta) {
  return (meta?.records && meta.records[BEST_KEY]) || null
}

/**
 * Сводка для экрана: рекорд + жар, вместе.
 *
 * Считается одной функцией, чтобы экран входа показывал обе причины
 * повторить, а не одну из них.
 */
export function reasonsToRun(meta) {
  const b = bestRecord(meta)
  return {
    best: b,
    heat: meta?.heatLevel || 0,
    // Одна строка для игрока. Если рекорда нет — приглашение, а не отчёт.
    line: b
      ? `Рекорд: ${b.pacified} оков снято${b.kills === 0 ? ', без единой крови' : `, крови ${b.kills}`}` +
        (b.revivals ? ` · с ${b.revivals} возвратом из смерти` : '')
      : 'Рекорда ещё нет — первый забег станет первым.',
  }
}
