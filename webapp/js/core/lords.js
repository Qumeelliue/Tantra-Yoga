// ТРОНЫ ЧАКРЫ: выбор владыки из трёх (Slay the Spire: три кандидата-босса).
//
// Откуда взято. В StS в начале акта на карте сверху стоят три значка боссов:
// игрок видит, кто его ждёт, и строит маршрут, считаясь с ним. Без этого
// босс — сюрприз, а не задача. У нас маршрут-карты нет (Поле Ума идёт
// комнатами), но само знание «кого я встречу» нужно ровно для того же:
// взять ли перед страшным троном лавку.
//
// Что копируется 1:1:
//
//   · **три кандидата показаны ДО того, как игрок пойдёт по этапу**;
//   · **выбирает игрок**, и выбор отменяется только смертью;
//   · **кто выбран — тот и на двери**: дверь владыки пишет его имя
//     (старый экран дверей, МЕХАНИКА 47), то есть обещание на двери и
//     содержимое комнаты совпадают;
//   · **состав тронов идёт через переданный `rng`**, а не через
//     `Math.random`: иначе замер мерил бы не тот забег, который играется —
//     ровно та ошибка, что была с `calmMul` и с несуществующим третьим
//     вариантом на узле практики (МЕХАНИКА 43).
//
// Кто на троне. Ни одно имя не выдумано (`design/BASE-GAME.md`, МЕХАНИКА 58):
// девять новых владык — те самые оковы, что уже встречаются в комнатах
// (Нидра, Бхая, Грна, Шаунка, Джугупса, Мана, Ладжа, Шила, Кула), пять —
// подлинные термины Шастр, уже названные в лоре самой игры или в Шанчаре:
// Кулакундалини, Самкальпа, Викальпа, Картта, Санчара. Три владыки одной
// чакры — три лица того, что её держит: у Вишуддхи это зависть, гордость
// культурой и знатность рода, и все трое затыкают горло.
//
// ЧЕГО НЕТ: пул у чакры — ровно три (не больше). Поэтому набор тронов задан
// чакрой, а разнообразие забега даёт выбор, порядок тронов и раскладки комнат.
// Расширить пулы — контентная работа, а не механика.

import { ENEMIES, worldForFloor } from './data.js'

/** Сколько тронов показываем. В StS — три кандидата. */
export const LORD_CHOICES = 3

/**
 * Троны чакры: id владык из `world.lordPool`.
 * Если пула нет (старый контент) — берётся `lordId`, то есть поведение
 * ровно прежнее: один владыка, никакого выбора.
 */
export function lordPool(floor) {
  const world = worldForFloor(floor)
  if (!world) return []
  const pool = Array.isArray(world.lordPool) && world.lordPool.length
    ? world.lordPool
    : (world.lordId ? [world.lordId] : [])
  return pool.filter((id) => !!ENEMIES[id])
}

/** Есть ли у этапа владыка. Отдельная функция — «есть ли владыка у ЭТАПА» и
 *  «есть ли владыка в СОБРАННОЙ КОМНАТЕ» — разные вопросы (см. `stageHasBoss`). */
export function stageHasLord(floor) {
  return lordPool(floor).length > 0
}

/**
 * Розыгрыш тронов. Генератор ОБЯЗАТЕЛЕН: троны — часть забега, и замер должен
 * видеть ровно тот забег, который играется.
 *
 * @returns {string[]} от 1 до LORD_CHOICES id, без повторов, порядок случайный
 */
export function rollLords(floor, rng) {
  // Генератор обязателен, и это не формальность: если бы троны падали из
  // `Math.random`, замер мерил бы не тот забег, который играется. Падать
  // здесь лучше, чем разойтись с игрой молча (как `rollDoors`).
  if (typeof rng !== 'function') throw new TypeError('rollLords: нужен rng — троны обязаны повторяться')
  const pool = lordPool(floor).slice()
  // Тасуем копию, а не пул контента: иначе первый забег переставил бы пул
  // в самом `content/` и следующий забег начинался бы с другого набора.
  for (let s = pool.length - 1; s > 0; s--) {
    const j = Math.floor(rng() * (s + 1)) % (s + 1)
    const tmp = pool[s]; pool[s] = pool[j]; pool[j] = tmp
  }
  return pool.slice(0, Math.max(1, Math.min(LORD_CHOICES, pool.length)))
}

/** Владыка этапа по id. Не берём id извне вслепую — сверяем с пулом чакры:
 *  иначе в комнату мог бы попасть владыка чужой чакры (числа и цитаты не его). */
export function lordFor(floor, id) {
  const pool = lordPool(floor)
  if (!id || !pool.includes(id)) return pool[0] || null
  return id
}

/** Короткое имя для двери и плашки: «Моха». */
export function lordName(id) {
  return (ENEMIES[id] && ENEMIES[id].name) || ''
}

/** Чакра владыки — по ней в Городе зажигается площадь (§14.1). */
export function lordChakra(id) {
  const d = ENEMIES[id]
  return d && typeof d.chakra === 'number' ? d.chakra : null
}

/** Все владыки, встречающиеся в игре: 7 чакр × 3 трона. Только для проверок. */
export function allLordIds() {
  const out = []
  for (let f = 0; f < 7; f++) out.push(...lordPool(f))
  return out
}