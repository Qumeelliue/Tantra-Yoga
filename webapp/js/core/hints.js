/** Кто ещё не исчерпал свои показы. */
export function availableHints(seen = {}) {
  return HINTS.filter((h) => (seen[h.id] || 0) < h.times)
}

/**
 * Подсказка для этого кадра: первая по порядку, чьё условие сработало.
 *
 * Порядок в реестре = приоритет. Критичные идут первыми, и всё, что может
 * совпасть с окном дефлекта, объявлено раньше подсказок-пояснений.
 */
export function pickHint(st, seen = {}) {
  if (!st) return null
  for (const h of availableHints(seen)) {
    const target = h.when(st)
    if (target !== null && target !== undefined && target !== false) {
      return { id: h.id, text: h.text, target }
    }
  }
  return null
}

/** Отметить, что подсказку показали. Счётчик, а не флаг: 3 показа — 3 раза. */
export function markHint(seen, id) {
  if (!seen || !id) return seen
  seen[id] = (seen[id] || 0) + 1
  return seen
}

/**
 * Подсказка не должна занимать место важного. Возвращает `true`, если сейчас
 * можно её показать: окно дефлекта открыто — на экране «ЖМИ ДЕФЛЕКТ».
 */
export function hintAllowed(st) {
  for (const f of st.foes || []) {
    if (f.dead || f.pacified) continue
    if (f.state === 'telegraph' && f.timer <= st.o.parryWindow) return false
  }
  return true
}
