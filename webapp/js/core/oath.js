// ОБЕТ — копия из Hades (Nya / Fear): назвать то, чего ты НЕ будешь делать,
// и получить награду, если сдержишь.
//
// Зачем. Все механики сейчас дают игроку выбор «что взять». Обет даёт выбор
// «от чего отказаться». Это разные вещи: жар и элита — ставка на силу, обет —
// ставка на дисциплину. В Hades это ровно то, чем берут Furies и Fear: чем
// строже условие, тем дороже награда.
//
// Скопировано 1:1:
//
//   · **выбираешь до забега, а не в середине** (иначе это не условие, а
//     подгонка результата);
//   · **награда за соблюдение, а не штраф за нарушение** — в Hades Nya
//     именно так и устроен: нарушил — просто ничего не получил;
//   · **чем строже условие, тем дороже награда**.
//
// Правила, без которых механика враньё:
//
//   1. **нарушенный обет не отменяется задним числом.** Он остаётся в отчёте
//      забега, потому что иначе «соблюдён» можно было бы задним числом
//      объявить чем угодно;
//   2. **обет виден во время забега**, а не всплывает в конце: условие, о
//      котором игрок не знает, нельзя соблюсти;
//   3. **проверка идёт по фактам забега** (`finishFieldRun` получает сводку),
//      а не по флагам, которые могли забыть сбросить.

/**
 * Список обетов. `broken` получает сводку забега и возвращает текст нарушения,
 * либо null, если обет соблюдён.
 */
export const OATHS = [
  {
    id: 'no_legend',
    name: 'Без легендарных',
    text: 'Не брать легендарные дары ни разу за забег.',
    reward: 4,
    broken: (r) => (r.legendary > 0 ? `взято легендарных: ${r.legendary}` : null),
  },
  {
    id: 'no_revive',
    name: 'Без возврата',
    text: 'Не возвращаться из смерти: умри — и начинай сначала.',
    reward: 6,
    broken: (r) => (r.revivals > 0 ? `возвратов из смерти: ${r.revivals}` : null),
  },
  {
    id: 'no_chaos',
    name: 'Без хаос-пути',
    text: 'Не брать дар даром: ни одной хаос-двери и ни одного хаос-пути.',
    reward: 5,
    broken: (r) => (r.chaos > 0 ? `хаос-путей взято: ${r.chaos}` : null),
  },
  {
    id: 'no_elite',
    name: 'Без испытания',
    text: 'Не заходить в испытание силы: плати нефритом за силу не хочешь.',
    reward: 4,
    broken: (r) => (r.elites > 0 ? `испытаний пройдено: ${r.elites}` : null),
  },
  {
    id: 'no_blood',
    name: 'Без крови',
    text: 'Пройти весь забег, не сломав ни одной оки.',
    reward: 8,
    broken: (r) => (r.kills > 0 ? `сломано силой: ${r.kills}` : null),
  },
]

/** Обет по id, либо null. */
export function oathById(id) {
  return OATHS.find((o) => o.id === id) || null
}

/**
 * Проверить обет по сводке забега.
 * @returns {{id:string,name:string,reward:number,kept:boolean,why:string|null}}
 */
export function checkOath(id, summary) {
  const o = oathById(id)
  const r = summary || {}
  if (!o) return { id: null, name: '', reward: 0, kept: false, why: null }
  const why = o.broken(r)
  return { id: o.id, name: o.name, reward: o.reward, kept: !why, why }
}

/**
 * Долг по обету: сколько севы ждёт игрока за уже сыгранные забеги.
 * Читает историю забегов, а не живёт в памяти сессии — иначе обет, сыгранный
 * в прошлой жизни, исчезал бы при перезаходе.
 */
export function owedFromLog(runLog = [], oathId = null) {
  let total = 0
  for (const row of runLog) {
    if (!oathId) continue
    const chk = checkOath(oathId, row)
    if (chk.kept) total += chk.reward
  }
  return total
}