/**
 * ПРИЁМЫ УРОВНЕЙ (Hades: у оружия с уровнем появляются НОВЫЕ ДВИЖЕНИЯ).
 *
 * **Почему не «+4 жизни за уровень».** В Hades уровень оружия открывает
 * новый приём, а не увеличивает урон того же. У нас уровень давал только
 * +4 макс. жизни: четыре ступени лестницы читались как «живучий понемногу».
 * Теперь каждая ступень — отдельный приём своей варны.
 *
 * **Где брались числа.** Не «по ощущению», а измерением. Проба каждого слота
 * боя (`npm run field-balance -- 30 -- --sloppy=0.85 --slots`) показала, какие
 * величины вообще двигают забег:
 *
 *   · окно парирования +13 из 30, крипа +12, прама +11 — тяжёлые;
 *   · скорость оков +5, сила дефлекта +4, серия +4, радиус успокоения +3;
 *   · замах владыки, «ход» щита, запас Ци, гашение неведения — слабые, но
 *     живые;
 *   · удар по паше, аура, щит за севу, Ци за снятую оку — **мёртвые**: бот
 *     ими не пользуется. Приёмы на них не ставятся.
 *
 * Каждая величина проверена ещё и на занятость: тяжёлые слоты делят с
 * мастерской и дарами. Это НЕ беда — в Hades аспект оружия и усиление зеркала
 * ночи меняют одно и то же оружие, это разные покупки одного предмета.
 *
 * **Правило, которое нельзя нарушать.** Приём уровня не дублирует приём
 * своей же варны: иначе это тот же приём, посчитанный дважды, — ровно та
 * болезнь, что была с легендарными дарами.
 *
 * `@param lv` — уровень ментальности 0…3. `apply(o, lv)` получает опции и
 * уровень, поэтому уровень применяется ОДИН раз на ступень, а не кумулятивно
 * по кругу.
 */
export function varnaRiders(id) {
  const kit = VARNA_KITS[id]
  return (kit && kit.riders) || []
}

export function applyVarna(opts, id, level = 0) {
  const o = { ...DEFAULT_FIELD_OPTIONS, ...opts }
  const kit = VARNA_KITS[id]
  if (kit) kit.apply(o)
  // Уровень — отдельный слой. Ранги применяются по порядку 1 → 2 → 3, как в
  // мастерской: иначе перестановка ступеней ломала бы забег.
  const lv = Math.max(0, Math.min(3, Number(level) || 0))
  for (let i = 0; i < lv; i++) {
    const rider = kit && kit.riders && kit.riders[i]
    if (typeof rider === 'function') rider(o)
  }
  for (const key of Object.keys(o)) if (typeof o[key] === 'number' && !Number.isFinite(o[key])) o[key] = DEFAULT_FIELD_OPTIONS[key]
  return o
}
