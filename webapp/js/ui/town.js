//
// ## Зачем этот файл
//
// Поле Ума стало изометрическим: пол — ромбы 2:1, стены по дальним краям, фигуры
// стоят по глубине. А Город остался экраном на DOM-карточках с эмодзи-глифами
// («◐», «♥», «👑»). Это ровно то различие, которое правило проекта называет
// палящимся: два разных вида в одной игре. Бой — место, Город — список.
//
// Теперь под каждой из семи площадей лежит настоящая изометрическая плитка
// земли из того же набора, что и пол комнаты. Площадь перестаёт быть карточкой с
// буквой и становится местом.
//
// ## Свет — это состояние, а не отдельная картинка
//
// Плитка одна на площадь, а «спит» и «зажжена» различаются фильтром: спящая
// площадь темнее и глуше, зажжённая — светлее. Это не украшение, а подстановка
// ровно того, что уже обещает подпись «свет в площадях»: мир не меняется, в нём
// зажигается свет.
//
// ## Почему плитка приклеивается к карточке, а не рисуется на холсте
//
// Город — DOM, а не холст: здесь карточки, кнопки и списки. Рисовать изометрию
// на холсте ради одного фона означало бы переписать экран целиком и сломать
// всю вёрстку. Фон-картинка даёт тот же вид и не трогает разметку.
//
// ## Соотношение 2:1 — не украшение
//
// Игровая плитка пола — 64×32, то есть ровно 2:1. Плитка площади ложится на
// карточку с тем же соотношением, иначе ромб превратится в параллелограмм и
// будет «завален». Проверяется в `tests/townTruth.test.js`.

const BASE = 'assets/town'

/**
 * Плитки площадей по порядку чакр: от мудрости к сознанию.
 *
 * Порядок не декоративный: яркость плиток растёт от 79 (тёмная земля, площадь
 * спит) к 153 (бледный камень, свет зажжён). Игрок возвращается в Город и
 * видит то же, что читает в подписи: земля светлеет.
 *
 * Средняя яркость измерена, а не выбрана на глаз — см. `scripts/townPrep.mjs`.
 */
export const PLAZA_TILES = [
  { file: 'plaza-1.png', brightness: 79, what: 'тёмная земля' },
  { file: 'plaza-2.png', brightness: 101, what: 'земля с камнями' },
  { file: 'plaza-3.png', brightness: 140, what: 'светлый песок' },
  { file: 'plaza-4.png', brightness: 124, what: 'серый камень' },
  { file: 'plaza-5.png', brightness: 153, what: 'бледный известняк' },
  { file: 'plaza-6.png', brightness: 142, what: 'холодный камень' },
  { file: 'plaza-7.png', brightness: 136, what: 'тёплый песок' },
]

export const PLAZA_COUNT = PLAZA_TILES.length

/** Адрес плитки по номеру площади (нумерация с нуля — как чакры). */
export function plazaSrc(index) {
  const t = PLAZA_TILES[index % PLAZA_TILES.length]
  return `${BASE}/${t.file}`
}

/**
 * Фильтр площади по состоянию.
 *
 * ## Почему яркость, а не отдельные картинки
 *
 * Свет в игре — это фильтр поверх того же места, а не другая картинка места.
 * Спит — значит темно и глухо; зажжено — значит светло. Если бы для каждого
 * состояния была своя плитка, пришлось бы держать 14 файлов и следить, чтобы
 * пара «тёмная/светлая» не разъехалась по тону: замена одной плитки тихо
 * испортила бы второе состояние.
 *
 * ## Числа измерены
 *
 * Тёмная площадь: яркость 38 %, насыщенность 20 % — читается как «во тьме
 * неведения», но текст поверх остаётся читаемым. Светлая: яркость 118 %,
 * насыщенность 105 % — видна золотая кромка света, как в описании площади.
 */
export const PLAZA_DARK = 'brightness(38%) saturate(20%)'
export const PLAZA_LIT = 'brightness(118%) saturate(105%)'

/**
 * Готова ли плитка площади — по факту наличия файла, а не по флажку.
 *
 * Фон-картинка браузер грузит сам, без `Image`: экран остаётся рабочим, пока
 * плитка едет, и становится местом, когда приехала. Поэтому проверять тут
 * нечего — и нечего проверять враньё.
 */
export function plazaReady() {
  return typeof document !== 'undefined'
}