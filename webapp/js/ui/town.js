// УЧАСТКИ ПЛОЩАДЕЙ ГОРОДА — ЗЕМЛЯ И ДОМ.
//
// ## Зачем этот файл
//
// Поле Ума стало изометрическим: пол — ромбы 2:1, стены по дальним краям, фигуры
// стоят по глубине. Город долго оставался экраном на DOM-карточках с эмодзи-
// глифами («◐», «♥», «👑») — ровно то различие, которое правило проекта
// называет палящимся: два разных вида в одной игре.
//
// Сначала под каждой площадью появилась изометрическая земля (МЕХАНИКА 63).
// Теперь на земле стоит дом: участок 2×2 плитки, на задней — дом из того же
// лицензионного набора, что и земля комнаты. Площадь — не карточка с буквой,
// а место, куда можно прийти.
//
// ## Дом собран скриптом, а не разложен по слоям в вёрстке
//
// Три картинки (земля, стены, крыша) сошлись в один файл `plot-N.png` в
// `scripts/townHouses.mjs` (`npm run houses:prep`). Слои в CSS пришлось бы
// выравнивать тремя `background-position`, которые нечем проверить; собранный
// участок проверяется как файл — кромки, дом над землёй, воспроизводимость.
//
// ## Свет — это состояние, а не вторая картинка
//
// Плитка одна на площадь, а «спит» и «зажжена» различаются фильтром: спящая
// площадь темнее и глуше, зажжённая — светлее. Это подстановка ровно того, что
// уже обещает подпись: мир не меняется, в нём зажигается свет. Дом — часть той
// же картинки: он темнеет и светлеет вместе с землёй, и отдельных «тёмных» и
// «светлых» домов держать не надо (пара картинок разъехалась бы по тону).
//
// ## Почему фон-картинка, а не холст
//
// Город — DOM: карточки, кнопки, списки. Рисовать изометрию на холсте ради
// одного фона означало бы переписать экран целиком и сломать вёрстку. Фон-картинка
// даёт тот же вид и не трогает разметку. Соотношение задано в CSS
// (`aspect-ratio: 272 / 226`), иначе участок «поплывёт».
//
// ## Числа участков измерены
//
// Средняя яркость участка записана — от 73 (тёмная земля, бурый дом) к 121
// (холодный камень, серо-синий дом). Числа сверяются с картинками в
// `tests/townHousesTruth.test.js`: если файл подменят, проверка упадёт, а не
// «подпись разойдётся с экраном».

const BASE = 'assets/town'

