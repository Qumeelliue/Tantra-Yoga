// Чипы взятых реликвий — маленький кусок вида, вынесенный ради проверки.
//
// ## Почему отдельно
//
// Пока отрисовка чипов жила внутри `screens/field.js`, единственная возможная
// проверка смотрела в исходник: сам экран-модуль в тестах не импортируется —
// его читают как текст. Проверка «в исходнике есть `fr-chip`» была зелёной и
// тогда, когда чипы собирались и НЕ рисовались. Она спрашивала «слово есть», а
// нужно «узел есть».
//
// Здесь ровно та же ловушка, что и с невставленной левой колонкой Поля Ума:
// узел есть в коде, его нет на экране, и проверка этого не видит.

import { h } from './dom.js'
import { fieldRelicView } from '../core/fieldRelics.js'

/**
 * @param {string[]} ids id реликвий забега
 * @returns {Array} узлы для вставки в список. Пустой вход — пустой выход:
 *   ненулевой набор должен означать хоть одну настоящую реликвию, иначе
 *   игрок увидит пустые плашки, а это хуже, чем ничего.
 */
export function relicChips(ids = []) {
  const out = []
  for (const id of ids) {
    const v = fieldRelicView(id)
    if (!v) continue
    // Подсказка — правдивое описание Поля Ума, а не карточное. В титуле чипа
    // игрок читает то же, что читал на карточке выбора.
    out.push(h('span', { class: `fr-chip ${v.rarity}`, title: v.desc }, v.name))
  }
  return out
}
