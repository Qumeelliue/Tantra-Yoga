// ИЗОМЕТРИЯ: ПРОЕКЦИЯ И ПОРЯДОК ГЛУБИНЫ.
//
// ## Зачем этот файл
//
// Автор: «мы же должны делать игру как Герои 3 или 5 — красивую». Это не про
// картинку, а про геометрию: поле сверху (прямоугольник, видно всю комнату)
// становится ромбом, появляется глубина, и кто ближе — тот впереди и больше.
//
// ## Решение: игра считает в плоскости, рисует в ромбе
//
// Ключевой выбор: **логика боя остаётся в прямоугольных координатах**, а
// изометрия появляется только при отрисовке. То есть `field.js` не переписывается
// вообще: сближение, радиусы, попадания, камера — всё как было.
//
// Почему так, а не «перевести игру на ромбы»:
//   - вся боевая математика уже проверена и покрыта тестами;
//   - ромб — это **преобразование при выводе**, а не новая система координат;
//   - если позже понадобится вид сверху (для тактического экрана, например),
//     логика останется той же, поменяется только проекция.
//
// ## Формула
//
// Стандартная изометрия с ромбом 2:1 (её требуют CC0-наборы Screaming Brain:
// плитка 128×64, ровно вдвое):
//
//     sx = (x - y) · (TILE_W / 2)
//     sy = (x + y) · (TILE_H / 2)
//
// Обратное преобразование нужно для ввода: палец лежит на экране, а игрок
// двигается в плоскости.
//
//     x = (sx / (TILE_W/2) + sy / (TILE_H/2)) / 2
//     y = (sy / (TILE_H/2) - sx / (TILE_W/2)) / 2
//
// ## Глубина
//
// Кто дальше по сумме x+y — тот впереди. Это ровно «ниже по экрану», поэтому
// сортировка по глубине совпадает с порядком отрисовки и не требует отдельного
// сравнения «выше/ниже по кадру».

/**
 * Плитка на ЭКРАНЕ и плитка в МИРЕ — разные числа, и путать их нельзя.
 *
 * `TILE_W`/`TILE_H` — размер ромба на экране (64×32, вдвое шире высоты, как
 * требует набор 128×64 уменьшенный вдвое).
 * `TILE_WORLD` — сколько мировых единиц занимает одна плитка по плоскости.
 *
 * Первая версия проекции умножала мировые координаты на `TILE_W/2` и получала
 * ромб высотой 40960 вместо 640 — то есть в 64 раза больше комнаты. Поймала
 * проверка чисел: глазом это увиделось бы как «графика съехала», а по коду
 * выглядело как обычно написанное преобразование.
 */
export const TILE_W = 64
export const TILE_H = 32
/** Мировых единиц на плитку по плоскости. */
export const TILE_WORLD = 64

/** Комната в плитках. 20×20 даёт ромб 1280×640 — ровно в видимую область по высоте,
 *  и камера ездит только влево-вправо, как в Heroes. */
export const ROOM_TILES = 20

/** Размер комнаты в плоских единицах: плитки × TILE_W. */
export const ROOM_W = ROOM_TILES * TILE_W
export const ROOM_H = ROOM_TILES * TILE_W

/** Проекция плоских координат в изометрические экранные. */
export function toIso(x, y) {
  const tx = x / TILE_WORLD
  const ty = y / TILE_WORLD
  return { x: (tx - ty) * (TILE_W / 2), y: (tx + ty) * (TILE_H / 2) }
}

/** Обратная проекция — для касаний. */
export function fromIso(sx, sy) {
  const a = sx / (TILE_W / 2)
  const b = sy / (TILE_H / 2)
  return { x: ((a + b) / 2) * TILE_WORLD, y: ((b - a) / 2) * TILE_WORLD }
}

/**
 * Глубина объекта: чем больше, тем ближе к зрителю и тем позже рисуется.
 *
 * Общая карта смещена так, чтобы ромб комнаты начинался с нуля: иначе в
 * отрисовке появляются отрицательные координаты, и пол уезжает влево-вверх.
 */
export function depth(x, y) {
  return x + y
}

/** Сдвиг всей комнаты так, чтобы ромб лежал в положительных координатах. */
export const ISO_OFFSET_X = (ROOM_H / TILE_WORLD) * (TILE_W / 2)
export const ISO_OFFSET_Y = 0

/** Проекция с уже применённым сдвигом — то, чем рисует экран. */
export function toIsoRoom(x, y) {
  const p = toIso(x, y)
  return { x: p.x + ISO_OFFSET_X, y: p.y + ISO_OFFSET_Y }
}

/**
 * Границы ромба в экранных координатах.
 *
 * Нужны для камеры: камера обязана знать, где кончилась комната, иначе она
 * покажет пустоту за краем. У прямоугольника это четыре числа, у ромба — четыре
 * угла.
 */
export function isoBounds() {
  const c = [
    toIsoRoom(0, 0),
    toIsoRoom(ROOM_W, 0),
    toIsoRoom(0, ROOM_H),
    toIsoRoom(ROOM_W, ROOM_H),
  ]
  return {
    x0: Math.min(...c.map((p) => p.x)),
    x1: Math.max(...c.map((p) => p.x)),
    y0: Math.min(...c.map((p) => p.y)),
    y1: Math.max(...c.map((p) => p.y)),
  }
}

/**
 * Затемнение: насколько плитка «в глубине».
 *
 * В Heroes дальний край комнаты темнее. Это не украшение — без этого ромб
 * читается как плоская шахматная доска, а не как место.
 */
export function depthShade(x, y, strength = 0.45) {
  const d = depth(x, y) / (ROOM_W + ROOM_H)
  return 1 - strength * (1 - Math.min(1, Math.max(0, d)))
}
