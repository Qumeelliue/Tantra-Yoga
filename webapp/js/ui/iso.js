//
// ## Зачем этот файл
//
// Автор: «нормальная игра, а не мусор 2д». 2д-мусор — это когда сценарий
// нарисован на прямоугольной сетке. Нормальная игра смотрится сверху-сбоку:
// комната — ромб, кто дальше — тот впереди, у дальнего края темнее. Всё это
// держится на **одном преобразовании**, и оно обязано быть в одном месте.
//
// ## ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА
//
// Обратное преобразование обязано быть обратным. В прошлый раз это было не так:
// прямая проекция прибавляла сдвиг комнаты (чтобы ромб лежал в положительных
// координатах), а обратная — не вычитала. Палец уезжал на 1280 мировых единиц
// от места, где стоит ока, то есть в другой конец комнаты. Числа в коде были
// «красивые», четыре проверки телефона падали.
//
// Поэтому здесь **нет** «проекции без сдвига». Есть ровно две функции:
//
//     roomIso(x, y)     — где в ромбе стоит точка плоскости
//     roomWorld(sx, sy) — какой точке плоскости соответствует пиксель ромба
//
// и `roomWorld(roomIso(x, y)) === (x, y)` проверяется тестом на сотнях точек.
// Сдвиг наружу не торчит: его нельзя «забыть вычесть», потому что его некуда
// вычитать — он спрятан внутри обеих функций.
//
// ## Числа
//
// Плитка 128×64 из наборов Screaming Brain уменьшается вдвое до 64×32 —
// соотношение 2:1 обязательно, иначе это не изометрия, а скосок.
//
// Мировая единица равна ширине плитки (TILE_WORLD = TILE_W = 64). Это сделано
// намеренно: **одна мировая единица = один пиксель на экране**. Значит, радиусы
// боя (удар за 32, сближение за 40) читаются на экране без пересчёта, и палец
// попадает туда, куда целится, без «коэффициента проекции».
//
//     sx = (x/64 − y/64) · 32 + сдвиг
//     sy = (x/64 + y/64) · 16
//
// Комната 14×14 плиток → ромб 896×448. Число не выбрано на глаз, а получено из
// двух требований, оба проверяются в `tests/isoMath.test.js`:
//
//   1. ромб по высоте помещается в телефон (448 ≤ 640) — иначе камера ездит
//      вверх-вниз и бой уезжает из-под пальца;
//   2. ПОЛНЫЙ бой помещается в кадр по ширине: оки стоят в кольце 0.30–0.70,
//      то есть ромб боя — 358 пикселей, и он уже экрана 420.
//
// Второе требование — не украшение. Предыдущая попытка (20 плиток, ромб 1280)
// выполняла первое и нарушала второе: ока уходила за кадр, и по ней нельзя было
// ни ударить пальцем, ни увидеть, что она идёт.

/** Плитка на экране. */
export const TILE_W = 64
export const TILE_H = 32
/** Мировых единиц на плитку по плоскости. */
export const TILE_WORLD = 64

/** Комната в плитках по каждой стороне. */
export const ROOM_TILES = 14

/** Комната в плоских единицах. */
export const ROOM_W = ROOM_TILES * TILE_WORLD
export const ROOM_H = ROOM_TILES * TILE_WORLD

/** Сдвиг ромба вправо, чтобы он лежал с нуля: левый угол комнаты — это ноль. */
export const ISO_OFFSET_X = ROOM_TILES * (TILE_W / 2)

/** Размер ромба комнаты в пикселях. */
export const ISO_W = ROOM_TILES * TILE_W
export const ISO_H = ROOM_TILES * TILE_H

/**
 * Плоскость → ромб комнаты. Левый угол комнаты стоит в нуле.
 *
 * @param {number} x — мировая координата, 0…ROOM_W
 * @param {number} y — мировая координата, 0…ROOM_H
 * @returns {{x: number, y: number}} — точка ромба, 0…ISO_W × 0…ISO_H
 */
export function roomIso(x, y) {
  const tx = x / TILE_WORLD
  const ty = y / TILE_WORLD
  return {
    x: (tx - ty) * (TILE_W / 2) + ISO_OFFSET_X,
    y: (tx + ty) * (TILE_H / 2),
  }
}

/**
 * Ромб → плоскость. Для касаний. Обратна `roomIso` **точно**.
 *
 * Сдвиг вычитается здесь, внутри. Наружу он не выставлен и не может быть
 * «забыт» — это и есть смысл, почему функция только одна.
 *
 * @param {number} sx — точка ромба, 0…ISO_W
 * @param {number} sy — точка ромба, 0…ISO_H
 * @returns {{x: number, y: number}} — точка плоскости
 */
export function roomWorld(sx, sy) {
  const a = (sx - ISO_OFFSET_X) / (TILE_W / 2)
  const b = sy / (TILE_H / 2)
  return { x: ((a + b) / 2) * TILE_WORLD, y: ((b - a) / 2) * TILE_WORLD }
}

/**
 * Глубина объекта: чем больше, тем ближе к зрителю и тем позже рисуется.
 *
 * Это ровно «ниже по экрану», поэтому сортировка по глубине совпадает с
 * порядком отрисовки и не требует отдельного сравнения «выше/ниже по кадру».
 */
export function depth(x, y) {
  return x + y
}

/** Границы ромба — в нём самом они всегда такие, и это проверяется. */
export function isoBounds() {
  return { x0: 0, x1: ISO_W, y0: 0, y1: ISO_H }
}

/**
 * Камера: не выходит за ромб и держит в кадре точку, за которой идёт.
 *
 * По вертикали ромб ниже экрана, поэтому камера может уходить в минус — это
 * «пустое небо» над комнатой, а не ошибка. Раньше та же проверка требовала
 * `cam.y ≥ 0`, и с изометрией это ломало бы вёрстку на ровном коде.
 *
 * @param {number} sx — точка ромба, за которой идёт камера
 * @param {number} sy — точка ромба
 * @param {number} viewW — ширина видимой области
 * @param {number} viewH — высота видимой области
 */
export function clampCamera(sx, sy, viewW, viewH) {
  const maxX = Math.max(0, ISO_W - viewW)
  const minY = Math.min(0, ISO_H - viewH)
  return {
    x: Math.max(0, Math.min(maxX, sx - viewW / 2)),
    y: Math.max(minY, Math.min(0, sy - viewH / 2)),
  }
}

/**
 * Затемнение по глубине: дальний край комнаты темнее.
 *
 * Это не украшение. Без этого ромб читается как плоская шахматная доска, а не
 * как место.
 */
export function depthShade(x, y, strength = 0.45) {
  const d = depth(x, y) / (ROOM_W + ROOM_H)
  return 1 - strength * (1 - Math.min(1, Math.max(0, d)))
}