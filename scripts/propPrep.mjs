//
// ## Зачем этот файл
//
// В Поле Ума четыре предмета остались нарисованными мной в коде: сокровище,
// фонтан амбросии, хаос (проклятая руна) и цветок на месте оковы. Правило
// проекта: **рисунок лицензионный, если лицензионный взять можно** — своё
// рисование допустимо только там, где лицензионного взять нечего.
//
// Лицензионное взять можно. Поэтому здесь каждая плитка выбрана **по замеру**,
// а не на глаз: плитки показаны силуэтом и долей непрозрачных пикселей, и только
// потом зафиксированы координаты.
//
// ## Откуда плитки (все CC0 — можно и в личной, и в коммерческой работе)
//
//   Сокровище (ящик)     Screaming Brain, 300+ Isometric Object Tiles
//   Фонтан (блок+вода)   тот же набор + 300+ Isometric Overworld Tiles
//   Хаос (лава)           IKSLM, Dungeon isometric tiles
//   Цветок (трава)        Screaming Brain, 300+ Isometric Overworld Tiles
//
// Полные адреса и условия — `webapp/public/assets/iso/SOURCES.md` и
// `webapp/public/assets/props/CREDITS.md`.
//
// ## Почему чёрный фон → альфа
//
// Наборы Screaming Brain отдаются в PNG **без альфа-канала**: ромб плитки лежит
// на чёрном фоне, а цвет прозрачности записан в `.tsx` строкой `trans="000000"`.
// Пока альфы нет, ящик рисуется как чёрный квадрат, а не как ящик. Ровно та же
// причина и у пола — там это уже сделано в `isoPrep.mjs`.
//
// ## Почему скрипт падает, если доля плитки поехала
//
// Момент, когда чинить придётся глазами, а глазом здесь не проверить: если после
// перевода альфы плитка стала на 80 % пустой или на 100 % непрозрачной, значит
// порог или координаты неверны. Поэтому скрипт печатает замер и падает.
//
// ## Что этот скрипт НЕ делает
//
// Не выбирает плитку. Выбор — это замер плюс решение, и оно зафиксировано ниже
// числами. Скрипт только приводит выбранное к виду, который читает браузер.

