/**
 * ЦВЕТА ПРОЗРАЧНОСТИ, ИЗМЕРЕННЫЕ В САМИХ ФАЙЛАХ.
 *
 * Не «как принято», а прочитано пикселями: угол листа `water.png` — малиновый
 * (255,0,255), угол `grass.png` и ящиков — чёрный (0,0,0). Набор говорит об
 * этом и на странице: «rendered with black or magenta backgrounds».
 *
 * Первая версия ключила только чёрным, и вода выходила 100 % непрозрачной —
 * то есть на экране был бы малиновый квадрат вместо воды. Это поймала проверка
 * по ожидаемой доле, а не глаза.
 */
const ROOT = join(fileURLToPath(new URL('..', import.meta.url)))
const SRC_DIR = join(ROOT, 'webapp/public/assets/props-src')
const OUT_DIR = join(ROOT, 'webapp/public/assets/props')

/** Доля непрозрачных пикселей в прямоугольнике. */
const share = (img) => {
  let op = 0
  for (let i = 3; i < img.data.length; i += 4) if (img.data[i] > 128) op++
  return op / (img.w * img.h)
}

/** Фон набора → альфа 0. Цвет фона берётся из самого файла, а не задаётся молча. */
const keyAlpha = (img, key = BLACK) => {
  for (let i = 0; i < img.data.length; i += 4) {
    const bg = img.data[i] <= key.r + KEY && img.data[i + 1] <= key.g + KEY
      && img.data[i + 2] <= key.b + KEY
    img.data[i + 3] = bg ? 0 : 255
  }
  return img
}

/**
 * Вырезать одну плитку из листа набора.
 *
 * `cut` — обрезка внутри плитки: у блока из Temple Kit плитка 104×80, а сам блок
 * занимает только её середину, и без обрезки в игру уехал бы пустой каменный
 * квадрат.
 */
export function cutTile(src, { col, row, tile = [0, 0], at, size, cut }) {
  const [tw, th] = tile
  const x0 = at ? at[0] : col * tw
  const y0 = at ? at[1] : row * th
  const w = cut ? cut.w : (size ? size[0] : tw)
  const h = cut ? cut.h : (size ? size[1] : th)
  const out = { w, h, data: Buffer.alloc(w * h * 4) }
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      // `+ x` обязателен. Без него адрес не двигался по горизонтали, и на выходе
      // получалась полоса из одного и того же пикселя вместо плитки: доля
      // непрозрачных была правильной (50 %), а на экране — вертикальная полоса.
      // Поймала проверка пикселей, а не доля.
      const s = ((y0 + (cut ? cut.y : 0) + y) * src.w + x0 + (cut ? cut.x : 0) + x) * 4
      const d = (y * w + x) * 4
      out.data[d] = src.data[s]
      out.data[d + 1] = src.data[s + 1]
      out.data[d + 2] = src.data[s + 2]
      out.data[d + 3] = src.data[s + 3]
    }
  }
  return out
}

/** Приготовить одну плитку: вырезать, снять чёрный фон, записать. Падает при отклонении. */
export function prepareOne(spec, srcDir = SRC_DIR, outDir = OUT_DIR) {
  const srcPath = join(srcDir, spec.src)
  if (!existsSync(srcPath)) throw new Error(`нет файла набора ${spec.src} — положить его в assets/props-src/`)
  const raw = keyAlpha(readPng(srcPath), spec.keyColor || BLACK)
  const tileImg = cutTile(raw, spec)
  const s = share(tileImg)
  if (s < spec.min || s > spec.max) {
    const where = spec.at ? `${spec.at[0]},${spec.at[1]}` : `${spec.col},${spec.row}`
    throw new Error(`плитка ${spec.out} (${where}) после перевода непрозрачна `
      + `на ${Math.round(s * 100)} %, ожидалось ${Math.round(spec.min * 100)}…${Math.round(spec.max * 100)} % `
      + '— либо порог неверный, либо выбрана не та плитка')
  }
  writePng(join(outDir, spec.out), tileImg.w, tileImg.h, tileImg.data)
  return { out: spec.out, size: `${tileImg.w}×${tileImg.h}`, opaque: Math.round(s * 100) }
}

if (String(process.argv[1] || '').endsWith('propPrep.mjs')) {
  let bad = 0
  for (const spec of CHOSEN) {
    try {
      const r = prepareOne(spec)
      console.log(`${r.out}: ${r.size}, непрозрачно ${r.opaque} %`)
    } catch (e) {
      bad++
      console.log(`${spec.out}: ПРОПУЩЕН — ${e.message}`)
    }
  }
  if (bad) process.exitCode = 1
}